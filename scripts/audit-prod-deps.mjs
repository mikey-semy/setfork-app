// ГЕЙТ ПО ЗАВИСИМОСТЯМ ПРИЛОЖЕНИЯ: high/critical в том, что уезжает на прод.
//
// Раньше здесь стояла прямая команда `npm audit --omit=dev --audit-level=high`. Она
// делает ровно то, что нужно, но у неё один код возврата на два разных события: «нашли
// уязвимость» и «не смогли спросить реестр». Второе — не про нас, а джоба краснела
// одинаково; за сутки 02–03.09.2026 это случилось дважды, и оба раза красный пришлось
// перезапускать. Так и приучаются не читать красный вообще.
//
// ⚠️ БЛОКИРУЮЩАЯ ПОЛОВИНА ОСТАЛАСЬ НАСТОЯЩЕЙ: найденная уязвимость валит джобу, как и
// раньше. Изменилось только то, что недоступность сервиса теперь предупреждение — и оно
// прямо говорит, что проверка НЕ отработала, а не притворяется чистотой.
import { fetchAuditReport, highOrCritical } from './lib/audit-report.mjs'

const gate = fetchAuditReport({ omitDev: true })
if (!gate.ok) {
  // Технические литералы уходят в лог CI, а не в интерфейс.
  console.log(`::warning::сервис аудита не отдал отчёт (${gate.why}) — гейт прод-зависимостей НЕ отработал; уязвимости при этом НЕ проверены`)
  process.exit(0)
}

const bad = highOrCritical(gate.report)
if (!bad.length) {
  console.log('Зависимости приложения: high/critical нет.')
  process.exit(0)
}
console.error('::error::в зависимостях, которые уезжают на прод, есть high/critical:')
for (const v of bad) console.error(`  ${v.name} (${v.severity}) — ${(v.via ?? []).map((x) => (typeof x === 'string' ? x : x.title)).join('; ')}`)
process.exit(1)
