/**
 * Идентичность блока сквозь версии — ОДНО определение на приложение.
 *
 * Живёт в домене, а не в фиче, потому что вопрос «тот же это блок» задают из
 * разных фич: `library` (структурный дифф, blame), `git` (three-way merge),
 * экспорт. Раньше каждая отвечала сама, и ответы разошлись — см. ниже.
 *
 * ДВА ИСТОЧНИКА, и это история, а не задел:
 *   • колонка `steps.block_id` — стабильная идентичность, введена ADR-0013;
 *   • `content.bid` — легаси-дом презентационных блоков (`text`, `quiz`, …),
 *     который редактор и MCP пишут до сих пор.
 *
 * На каноне 12.08.2026 из 494 блоков у 51 (31 `text`, 20 `quiz`) заполнен
 * ТОЛЬКО `content.bid`, колонка пуста.
 *
 * Чем это было опасно: дифф смотрел лишь колонку и для тех 51 блока
 * идентичности не находил — падал на фолбэк, а фолбэк у не-step блоков
 * считается ПО СОДЕРЖИМОМУ, то есть по тому самому, что правка и меняет.
 * Поэтому правка читалась как «блок удалён + блок добавлен»: комментарий
 * привязать не к чему, а blame и merge (они `content.bid` знали) отвечали
 * иначе. Линза 05, находка D1.
 *
 * Колонка сильнее `content.bid`: её проставляет редактор осознанно, а payload
 * может нести старое значение, приехавшее вместе с содержимым блока.
 */
export function blockIdentity(b: {
  blockId?: string | null
  content?: Record<string, unknown> | null
}): string | null {
  if (b.blockId) return b.blockId
  const bid = b.content?.bid
  return typeof bid === 'string' && bid ? bid : null
}

/**
 * ВСЕ идентичности блока — для СОПОСТАВЛЕНИЯ версий, где важно совпадение любой.
 *
 * Их бывает две одновременно, и это переход, а не дубль: легаси-блок хранит bid
 * в `content.bid`, а редактор при первом сохранении выдаёт ему ещё и uuid в
 * колонку (`editor.ts`: «в колонку кладём ТОЛЬКО uuid, легаси-bid живёт дальше в
 * content.bid»). Старая версия тогда опознаётся по bid, новая — по uuid; если
 * сравнивать одним значением, блок читается как «удалён + добавлен» ровно в
 * момент перехода. Замечание авто-ревью на fe#769.
 *
 * Порядок сохранён от `blockIdentity`: колонка сильнее — она и стоит первой.
 */
export function blockIdentities(b: {
  blockId?: string | null
  content?: Record<string, unknown> | null
}): string[] {
  const bid = b.content?.bid
  const legacy = typeof bid === 'string' && bid ? bid : null
  return [b.blockId || null, legacy].filter((x): x is string => !!x)
}
