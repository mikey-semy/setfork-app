/**
 * НОМЕР В ЗАГОЛОВКЕ: снять на записи, показать на своём месте при чтении.
 *
 * Порядковый номер пункта рисует карточка, номер секции — оглавление. Модель об этом не
 * знала и писала номер ещё и в сам текст: секция «1. Подтверждение оповещения», под
 * которой оглавление ставит свою единицу. Дубль владелец увидел на живом списке.
 *
 * Отсюда две разные функции, и обе нужны:
 *
 * `stripOrdinal` — на ЗАПИСИ. Одноуровневый номер интерфейс рисует сам, значит в тексте он
 * лишний и вдобавок ЛЖЁТ после перестановки пункта: порядок пересчитается, текст нет.
 *
 * `splitOrdinal` — на ЧТЕНИИ. Уже записанное так не исправить: список создан, номера лежат
 * в тексте, и убрать их можно только правкой с публикацией. Поэтому при показе номер из
 * текста уходит в колонку номера — ту самую, где интерфейс рисует свой. Дубля нет, а
 * многоуровневая нумерация автора («1.1», «1.2.3»), которую интерфейс выразить не умеет,
 * остаётся видимой — на своём месте.
 */

/** Одноуровневый номер в начале: «1. », «2) », «Шаг 3: ». Снимается на записи.
 *
 *  Форма узкая намеренно: номер, разделитель, ПРОБЕЛ. «1.5 л воды» и «7 способов» так не
 *  срежутся — там за разделителем нет пробела либо нет самого разделителя. Многоуровневая
 *  нумерация («1.1 Введение») тоже остаётся: её интерфейс не рисует, значит она не дубль,
 *  а сведения автора. */
const ORDINAL_PREFIX = /^\s*(?:(?:шаг|step)\s+)?\d{1,3}\s*[.):\]]\s+(?=\S)/i

/** Заголовок без ведущего номера. Текст без номера возвращается как есть. */
export const stripOrdinal = (s: string): string => s.replace(ORDINAL_PREFIX, '')

/** Номер любой глубины с ОБЯЗАТЕЛЬНЫМ разделителем: «1.», «1.1)», «2.3.4.».
 *
 *  Разделитель обязателен именно здесь, при показе: без него «1.5 л воды» неотличимо от
 *  «1.1 Введение», и заголовок рецепта развалился бы на номер «1.5» и текст «л воды».
 *  Не распознали — показываем как есть: недоубрать дубль лучше, чем испортить заголовок. */
const NUMBERED = /^\s*(\d{1,3}(?:\.\d{1,3})*)\s*[.)\]]\s+(?=\S)/

/** Заголовок → номер автора (если он есть) и остаток текста. */
export function splitOrdinal(s: string): { num: string | null; text: string } {
  const m = NUMBERED.exec(s)
  return m ? { num: m[1], text: s.slice(m[0].length) } : { num: null, text: s }
}
