/**
 * КАКАЯ ПОЛКА ПОДХОДИТ НОВОМУ СПИСКУ.
 *
 * Повод измерен: полки завели полгода назад, и к моменту пакетной раскладки на них лежало
 * 3 списка из 523. Разложить корпус разом теперь можно, но если новый список по-прежнему
 * рождается вне полок, через месяц библиотека расползётся снова — то есть вся уборка
 * окажется разовой (это и записано в мерке трека: доля вне полок через месяц).
 *
 * Подсказываем по ТЕГАМ, потому что это единственное, что у списка есть уже в момент
 * создания и что роднит его с соседями по полке. Заголовок для этого не годится: он
 * уникален по построению, у двух списков одной темы общих слов может не быть вовсе.
 *
 * Правило нарочно скупое — совпадение считается ПО ЧИСЛУ ОБЩИХ ТЕГОВ, и подсказка выдаётся,
 * только когда победитель СТРОГО впереди второго места. Ничья означает, что данные никуда
 * не показывают, и предложить в такой ситуации любую из полок — значит выдать подбрасывание
 * монеты за совет. Молчание честнее: человек выберет сам, а полка останется его решением.
 *
 * Порога «хотя бы N общих тегов» здесь нет и не нужно: один общий тег при отсутствии
 * конкурентов — это и есть весь сигнал, который дают данные, а показываем мы его вместе с
 * причиной («совпало: skill»), так что цена ошибки — одно нажатие.
 */

export interface CatalogProfile {
  name: string
  title: string
  /** Теги списков, уже лежащих на этой полке (без повторов). */
  tags: string[]
}

export interface CatalogGuess {
  name: string
  title: string
  /** Из-за чего предложили — показываем человеку, а не просим верить на слово. */
  shared: string[]
}

/** Полка, к которой новый список ближе всего по тегам, или null — если данные молчат. */
export function guessCatalog(tags: string[], profiles: CatalogProfile[]): CatalogGuess | null {
  const wanted = new Set(tags.filter(Boolean))
  if (!wanted.size || !profiles.length) return null

  const scored = profiles
    .map((p) => ({ profile: p, shared: p.tags.filter((tag) => wanted.has(tag)) }))
    .filter((s) => s.shared.length > 0)
    .sort((a, b) => b.shared.length - a.shared.length)

  const [best, runnerUp] = scored
  if (!best) return null
  if (runnerUp && runnerUp.shared.length === best.shared.length) return null
  return { name: best.profile.name, title: best.profile.title, shared: best.shared }
}
