// Транслитерация кириллицы и детект языка текста — общие для слагов (library),
// хендлов (auth) и MCP-создания списков.

/**
 * ⚠️ СХЕМА ЗАМОРОЖЕНА. Это СВОЯ таблица — не ГОСТ 7.79 и не ICAO 9303 (`щ→sch`, `х→h`,
 * `й→y`, `ё→e`), и менять её НЕЛЬЗЯ, даже «к стандарту»: из неё строятся слаги списков,
 * ники и имя скилла в SKILL.md. Добавлять буквы (украинские `і ї є ґ`, белорусская `ў`)
 * — тоже смена схемы: сейчас они проходят как есть, и `slugify` их вырезает. Другая буква в таблице — другие адреса у всего, что создадут после правки, и
 * расхождение со всем, что создано до: один и тот же заголовок давал бы два разных слага,
 * а поиск существующего по транслиту перестал бы находить старые адреса.
 * Решение — ревью соответствия 23.09 (setfork-hq/standards/transliteration.md); таблицу
 * держит `tests/shared/lib/translit.test.ts`. Нужна другая схема — это новое решение с
 * переездом адресов, а не правка этой строки.
 */
const RU_LAT: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z', и: 'i', й: 'y',
  к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f',
  х: 'h', ц: 'ts', ч: 'ch', ш: 'sh', щ: 'sch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
}

export function translitRu(s: string): string {
  return s
    .toLowerCase()
    .split('')
    .map((ch) => RU_LAT[ch] ?? ch)
    .join('')
}

/** Язык текста по доле кириллицы: ≥30% буквенных символов — русский. */
export function detectTextLang(text: string): 'ru' | 'en' {
  const letters = text.match(/[a-zA-Zа-яА-ЯёЁ]/g) ?? []
  if (!letters.length) return 'en'
  const cyr = letters.filter((ch) => /[а-яА-ЯёЁ]/.test(ch)).length
  return cyr / letters.length >= 0.3 ? 'ru' : 'en'
}
