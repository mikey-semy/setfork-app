/**
 * Плотность списка карточек — «просторно» или «плотно», по образцу переключателя вида
 * у GitHub в перечне репозиториев.
 *
 * Выбор живёт в КУКЕ, а не в адресе и не в localStorage. В адресе он засорял бы ссылку,
 * которой делятся, и уезжал бы вместе с ней чужому человеку; в localStorage сервер о нём
 * не знает и первый кадр приходил бы чужой плотности, а потом прыгал. Кука известна
 * обеим сторонам — тем же приёмом свёрнут сайдбар (`SIDEBAR_COOKIE`).
 *
 * Отдельным модулем, потому что константу просят обе стороны: сервер читает при рендере,
 * клиент пишет при переключении. Из `use client`-модуля серверу можно брать только
 * компоненты — правило под тестом `tests/architecture/rsc-client-boundary`.
 *
 * ⚠️ ЧИТАЕТ ЕЁ ПОКА ТОЛЬКО ПРОФИЛЬ. Кука общая (`path=/`) и переживёт год, но остальные
 * перечни списков — /explore, /tags, /search, /trending, каталоги — плотность
 * игнорируют и переключателя не показывают. Это осознанный первый шаг, а не забытые
 * места: переключатель просили для своей библиотеки, где списков сотни. Когда дойдёт
 * до остальных поверхностей, читать надо ТУ ЖЕ куку — заводить вторую нельзя, иначе
 * человек будет переключать вид дважды.
 */
export const DENSITY_COOKIE = 'sf_density'

export type ListDensity = 'comfy' | 'compact'

/** Просторно — по умолчанию: описание и теги видны без лишних действий. */
export function densityFrom(value: string | undefined): ListDensity {
  return value === 'compact' ? 'compact' : 'comfy'
}
