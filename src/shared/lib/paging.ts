/**
 * ОКНО ВЫДАЧИ, ПРОВЕРЕННОЕ ПЕРЕД ЗАПРОСОМ. Зовётся везде, где окно уходит в `.limit()`.
 *
 * Драйвер ставит предел так: `typeof limit === 'object' || (typeof limit === 'number' &&
 * limit >= 0)`. Всё прочее он МОЛЧА выбрасывает — и запрос уходит в базу без предела,
 * поднимая весь корпус. Ровно это и происходило на главной: `limit` приезжал не числом
 * (см. DASHBOARD_LISTS выше), предел исчезал, приходили все 518 списков, а ошибки не было
 * ни одной — поэтому четыре правки подряд выглядели верными и ничего не меняли.
 *
 * Отсюда правило: битое окно — это исключение, а не «ну покажем всё». Тихий полный скан
 * дороже пятисотки: пятисотку видно сразу, а скан живёт месяцами.
 *
 * Значение в сообщение НЕ подставляем, только `typeof`: подставить — значит тронуть его
 * (`String(x)` дёргает `valueOf`), а именно на этом ссылка на клиентский модуль и бросает,
 * подменяя понятную ошибку невнятной.
 */
export function feedWindow(window: { limit: number; offset?: number }): { limit: number; offset: number } {
  const { limit, offset = 0 } = window
  if (!Number.isInteger(limit) || limit <= 0) {
    throw new TypeError(`paging: limit must be a positive integer, got ${typeof limit}`)
  }
  if (!Number.isInteger(offset) || offset < 0) {
    throw new TypeError(`paging: offset must be a non-negative integer, got ${typeof offset}`)
  }
  return { limit, offset }
}

/**
 * ПОТОЛОК НОМЕРА СТРАНИЦЫ. Номер приходит из адреса, то есть от кого угодно.
 *
 * `?page=1e999` даёт `Infinity`: смещение перестаёт быть целым, и строгая проверка окна
 * роняет страницу пятисоткой. `?page=1e18` проверку проходит, но переполняет `bigint` в
 * `OFFSET` — падает уже база. Ни один настоящий человек не листает до миллионной страницы,
 * поэтому предел ставится здесь, а не разбирается на каждой поверхности.
 */
export const MAX_PAGE = 1_000_000

/** Окно запроса для страницы (нумерация с 1). Считается ЗДЕСЬ, чтобы `offset` не выводили
 *  руками на каждой странице: ошибка в этой арифметике тихо теряет или дублирует строки. */
export function pageWindow(page: number, perPage = LISTS_PER_PAGE): { limit: number; offset: number } {
  const safe = Math.min(Math.max(1, Math.floor(page) || 1), MAX_PAGE)
  return { limit: perPage, offset: (safe - 1) * perPage }
}

/** Сколько всего страниц. Ноль записей — всё равно одна страница: пустая выдача это
 *  состояние, а не отсутствие страницы. */
export function pageCount(total: number, perPage = LISTS_PER_PAGE): number {
  return Math.max(1, Math.ceil(total / perPage))
}

/**
 * Номер страницы из адреса: мусор и выход за край приводятся к существующей странице.
 *
 * ЦЕЛОЕ — обязательно. `?page=2.9` иначе доезжало сюда дробью и дальше расходилось со
 * всеми, кто номер округляет: окно просило вторую страницу, а листалка рисовала «2.9»,
 * не подсвечивала текущую и строила ссылку `?page=3.9000000000000004`. Округляем ВНИЗ
 * (`2.9` → вторая), потому что дробь — это всегда мусор в адресе, а не просьба.
 */
export function pageFromParam(raw: string | undefined, totalPages: number): number {
  const n = Math.floor(Number(raw)) || 1
  return Math.min(Math.max(1, n), Math.max(1, totalPages))
}

/** Имя параметра страницы. Одно на сайт: иначе «?page=» тут и «?p=» там. */
export const PAGE_PARAM = 'page'

/**
 * ССЫЛКА НА СТРАНИЦУ — один построитель на все листалки.
 *
 * Каждая страница писала его сама, и они разошлись: «мои списки» тащили дальше `sq`,
 * профиль — семь параметров, а тег и полка не тащили НИЧЕГО. То есть на второй
 * странице тега молча слетал выбранный порядок, а с полки — фильтр, и человек не мог
 * понять, куда делся отбор. Теперь остальные параметры переносятся всегда, а меняется
 * ровно один.
 *
 * Первая страница — БЕЗ `?page=1`: адрес у неё ровно один, иначе поисковик видит две
 * страницы с одним содержимым, а «поделиться ссылкой» даёт то один вид, то другой.
 */
export function pageHref(
  pathname: string,
  params: URLSearchParams | Record<string, string | number | undefined | null>,
  param = PAGE_PARAM,
): (page: number) => string {
  const qs = new URLSearchParams()
  const entries = params instanceof URLSearchParams ? [...params.entries()] : Object.entries(params)
  for (const [k, v] of entries) {
    if (k === param || v === undefined || v === null || v === '') continue
    qs.set(k, String(v))
  }
  return (page: number) => {
    const next = new URLSearchParams(qs)
    if (page > 1) next.set(param, String(page))
    const s = next.toString()
    return s ? `${pathname}?${s}` : pathname
  }
}

/**
 * ОКНО-РАЗВЕДЧИК: берём на одну строку больше, чем покажем.
 *
 * Так узнаётся «есть ли следующая страница» БЕЗ `count(*)`. Разница не косметическая:
 * счёт — это проход по всем подходящим строкам на КАЖДЫЙ показ страницы, и стоит он
 * тем дороже, чем больше корпус, — ровно то, ради чего пагинацию и заводили. Лишняя
 * же строка достаётся даром: она следующая в том же индексе, который запрос и так
 * читает.
 *
 * Платим за это номером последней страницы: с разведчиком листалка знает «дальше есть»,
 * но не знает «сколько всего». Там, где общее число и так посчитано для другого (счётчики
 * вкладок, «найдено N»), берём его — считать второй раз незачем.
 */
export function probeWindow(page: number, perPage = LISTS_PER_PAGE): { limit: number; offset: number } {
  const { limit, offset } = pageWindow(page, perPage)
  return { limit: limit + 1, offset }
}

/** Разбор выдачи разведчика: показываем страницу, лишняя строка — это ответ «дальше есть». */
export function takePage<T>(rows: T[], perPage = LISTS_PER_PAGE): { items: T[]; hasNext: boolean } {
  return { items: rows.slice(0, perPage), hasNext: rows.length > perPage }
}

/**
 * Номера для листалки: первая, последняя, окно вокруг текущей, между ними — многоточие.
 *
 * ДЛИНА РЯДА ПОСТОЯННА (2·around + 5 ячеек), и это не украшение. Ряд отцентрован, поэтому
 * лишняя ячейка сдвигает ОБЕ стрелки наружу примерно на их собственную ширину — палец,
 * уже занесённый над «вперёд», попадает мимо. Первая версия этого не держала: на 74
 * страницах третья давала шесть ячеек, а четвёртая семь, то есть ряд прыгал на обычном шаге.
 *
 * Постоянство даётся не подгонкой, а тремя случаями. У края окно разворачивается внутрь
 * (одно многоточие вместо двух), в середине их два. Заодно из построения следует, что за
 * многоточием НИКОГДА не прячется одна страница: прятать одну — обман без экономии места,
 * ячеек столько же, а страница недостижима в один клик.
 */
export function pageNumbers(page: number, totalPages: number, around = 1): (number | 'gap')[] {
  const cells = around * 2 + 5
  if (totalPages <= cells) return Array.from({ length: totalPages }, (_, i) => i + 1)
  const range = (from: number, to: number) => Array.from({ length: to - from + 1 }, (_, i) => from + i)
  // У начала: сплошной кусок от первой, одно многоточие, последняя.
  if (page <= around + 3) return [...range(1, cells - 2), 'gap', totalPages]
  // У конца — зеркально.
  if (page >= totalPages - (around + 2)) return [1, 'gap', ...range(totalPages - (cells - 3), totalPages)]
  // В середине: первая, многоточие, окно, многоточие, последняя.
  return [1, 'gap', ...range(page - around, page + around), 'gap', totalPages]
}

// ── Keyset: листание по КЛЮЧУ, а не по номеру ────────────────────────
//
// Зачем вообще второй механизм, когда номера работают. Смещение считается ОТ НАЧАЛА
// выдачи, а у ленты начало сдвигается: пока читают вторую страницу, сверху прилетают
// новые строки. Тогда `offset 20` указывает уже не туда, куда указывал минуту назад, и
// выдача становится не медленной, а НЕВЕРНОЙ: строка, стоявшая 21-й, уезжает на первую
// страницу и не показывается ни разу, а строка со второй страницы приходит ещё и на
// третью. Доопределение до `id` здесь бессильно — оно делает порядок однозначным внутри
// ОДНОГО снимка, а сдвинулось само начало отсчёта.
//
// Ключ от этого не зависит: «дай строки СТРОГО ПОСЛЕ вот этой» отвечает одинаково,
// сколько бы сверху ни добавили. Платим невозможностью прыгнуть на страницу N — поэтому
// keyset идёт туда, где такого прыжка и не просят (ленты читают сверху вниз), а номера
// остаются у каталогов, где прыжок — основной способ навигации.

/** Имя параметра курсора в адресе. Одно на сайт — как PAGE_PARAM. */
export const AFTER_PARAM = 'after'
/** Зеркальный шаг: «строки ПЕРЕД вот этой». Им и живёт «назад» у keyset. */
export const BEFORE_PARAM = 'before'
/** Все параметры курсора — чтобы шаг в одну сторону не тащил за собой другой (см. cursorHref). */
const CURSOR_PARAMS = [AFTER_PARAM, BEFORE_PARAM]

/**
 * Направление шага. Не «сортировка», а именно шаг: `after` — вниз по ленте (к более
 * старому), `before` — вверх (к более свежему). У обоих один и тот же порядок ПОКАЗА,
 * свежие сверху; отличается лишь то, с какой стороны от курсора берутся строки.
 */
export type FeedDirection = 'after' | 'before'

/**
 * Порядок ПОКАЗА ленты — отдельно от направления шага, и путать их нельзя.
 * `desc` — свежее сверху (уведомления, активность); `asc` — старое сверху (тред
 * обсуждения: читают с начала, дописывают в конец). От этого зависит, что «дальше»
 * значит в терминах времени: у ленты — в прошлое, у треда — в будущее.
 */
export type FeedOrder = 'desc' | 'asc'

/**
 * Курсор — пара «значение ключа сортировки + id».
 *
 * `key` — ТЕКСТ, ровно как его отдала база, а НЕ дата, прошедшая через JS. Это не
 * придирка: `timestamptz` в Postgres хранит МИКРОсекунды, а `Date` в JS — только
 * миллисекунды, и drizzle отдаёт типизированную колонку уже обрезанной. Замер 18.08:
 * в базе `19:02:03.092835`, в приложении `19:02:03.092Z` — то есть строка оказывается
 * СТРОГО ПОЗЖЕ собственного ключа, прошедшего через JS.
 *
 * Чем это кончается: условие `(key, id) < (:key, :id)` с обрезанным ключом отсекает не
 * только уже показанное, но и всё, что попало в отброшенные микросекунды, — строки
 * пропадают молча. Поэтому запрос обязан отдавать ключ курсора отдельной ТЕКСТОВОЙ
 * колонкой (`${column}::text`), а не собираться из типизированного значения.
 */
export interface Cursor {
  /** Значение ключа сортировки текстом из базы — с полной точностью. */
  key: string
  /** Доопределение: на равных ключах порядок задаёт он. */
  id: string
}

/** Курсор в адресе — одна строка, а не два параметра: половинки нельзя потерять порознь. */
const CURSOR_SEP = '~'
/** Потолок длины: курсор приходит из адреса, то есть от кого угодно. */
const CURSOR_MAX = 512
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i
/**
 * ТИП КЛЮЧА СОРТИРОВКИ. Не украшение: дальше ключ уходит в `::timestamptz` или `::int`,
 * и мусор там — это 500 на ровном месте вместо «покажем сначала».
 *
 * Тип спрашивается У ПОВЕРХНОСТИ, а не угадывается по виду строки. Иначе курсор от
 * ленты уведомлений, подставленный в адрес истории версий, доехал бы до `'2026-08-18
 * …'::int` и уронил страницу. Поверхность знает свой ключ; строка — нет.
 */
export type CursorKeyType = 'time' | 'int'

/** Текстовая форма `timestamptz` из Postgres: `2026-08-18 19:02:03.092835+00`. */
const TS_RE = /^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}(\.\d{1,6})?[+-]\d{2}(:\d{2})?$/
/**
 * Целое без плюса, ведущих нулей и хвостов: номер версии, счётчик.
 *
 * Форма — половина дела; вторая половина — ДИАПАЗОН. Ключ уходит в `::int`, а это int4:
 * `999999999999999999` проходит любую проверку формы, доезжает до базы и роняет запрос
 * «integer out of range». Ровно та пятисотка, которую этот разбор и обязан не допускать,
 * поэтому диапазон проверяется отдельно (`INT_MAX` ниже), а не подгонкой регулярки:
 * регулярка про цифры, а не про то, во что они превращаются в SQL.
 */
const INT_RE = /^-?(0|[1-9]\d{0,9})$/
/** Потолок int4 — типа, в который приводится целый ключ. */
const INT_MAX = 2_147_483_647

const toBase64Url = (s: string): string =>
  btoa(s).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '')

const fromBase64Url = (s: string): string | null => {
  try {
    return atob(s.replace(/-/g, '+').replace(/_/g, '/').padEnd(Math.ceil(s.length / 4) * 4, '='))
  } catch {
    return null
  }
}

/**
 * Курсор → строка для адреса.
 *
 * Кодируется, а не пишется как есть, по двум причинам: в тексте `timestamptz` есть `+`
 * и `:`, которые в query-string значат другое, и открытый курсор напрашивается на правку
 * руками. Base64 — НЕ защита (раскодировать может кто угодно), а ровно упаковка: защиту
 * даёт строгая проверка при разборе.
 */
export function encodeCursor(cursor: Cursor): string {
  const payload = `${cursor.key}${CURSOR_SEP}${cursor.id}`
  // `btoa` работает только с Latin-1 и на первой же кириллической букве бросает
  // `InvalidCharacterError`. Ключи keyset — метки времени и uuid, то есть ASCII, и
  // ломаться тут нечему; но если ключом однажды сделают текст (слаг, заголовок),
  // ошибка вылезет не здесь, а в браузере посреди листания. Поэтому проверяем сразу
  // и говорим, ЧТО не так: encodeCursor зовёт наш код своими данными — это ошибка
  // программиста, и она должна быть громкой (как в feedWindow), а не отложенной.
  if (!/^[\x20-\x7e]*$/.test(payload)) {
    throw new TypeError('paging: ключ курсора обязан быть ASCII — иначе base64 не построить')
  }
  return toBase64Url(payload)
}

/**
 * Строка из адреса → курсор. Любая кривизна — `null`, то есть «показать с начала».
 *
 * Тут НЕ бросаем, в отличие от `feedWindow`, и разница принципиальная. Битое окно тихо
 * превращается в «без предела» — это полный скан, который живёт месяцами незамеченным,
 * поэтому там исключение. Битый курсор превращается в «первая страница»: состояние
 * видимое, безвредное и ровно то, что человеку нужно, если он приехал по обломанной
 * ссылке. Так же поступает `pageFromParam` с мусорным номером.
 */
export function decodeCursor(raw: string | undefined | null, keyType: CursorKeyType = 'time'): Cursor | null {
  if (typeof raw !== 'string' || !raw || raw.length > CURSOR_MAX) return null
  const decoded = fromBase64Url(raw)
  if (decoded === null) return null
  const at = decoded.indexOf(CURSOR_SEP)
  if (at <= 0) return null
  const key = decoded.slice(0, at)
  const id = decoded.slice(at + CURSOR_SEP.length)
  // Разделитель ровно один: две пары в одном курсоре — признак подделки, а не опечатки.
  if (id.includes(CURSOR_SEP)) return null
  if (!(keyType === 'int' ? INT_RE : TS_RE).test(key) || !UUID_RE.test(id)) return null
  if (keyType === 'int' && Math.abs(Number(key)) > INT_MAX) return null
  return { key, id }
}

/**
 * ШАГ ИЗ АДРЕСА: какой курсор и в какую сторону.
 *
 * Шесть страниц читали эти три строки у себя, и это ровно то место, где копии стоят
 * дорого: перепутать `before` с `after` — молчаливая ошибка, которую видно только глазами
 * на живой странице, а ни один тест запросов её не увидит. Здесь она проверяется один раз.
 *
 * `before` разбирается ПЕРВЫМ и побеждает: одновременно их в адресе быть не может —
 * `cursorHref` выкидывает оба и ставит ровно один, — но адрес приходит от кого угодно, и
 * порядок должен быть определён, а не случаен.
 *
 * Мусор в обоих — начало ленты: ссылка могла обломаться в письме, и человеку нужна лента,
 * а не ошибка.
 */
export function readCursor(
  sp: { after?: string; before?: string },
  keyType: CursorKeyType = 'time',
): { cursor: Cursor | null; dir: FeedDirection } {
  const back = decodeCursor(sp.before, keyType)
  return back ? { cursor: back, dir: 'before' } : { cursor: decodeCursor(sp.after, keyType), dir: 'after' }
}

/**
 * Предел запроса-разведчика для keyset: на строку больше показанного.
 *
 * То же, что делает `probeWindow` для номеров, но без смещения — у keyset его нет вовсе.
 * Лишняя строка отвечает на «есть ли дальше» даром: она следующая в том же индексе,
 * который запрос и так читает. Разбирается тем же `takePage`.
 */
export function probeLimit(perPage = LISTS_PER_PAGE): number {
  // Проверяем ТАК ЖЕ строго, как `feedWindow` проверяет окно по смещению, и по той же
  // причине: непригодный предел драйвер выбрасывает молча, и запрос уходит в базу без
  // предела. Без этой проверки keyset был бы дырой ровно в том месте, ради которого
  // заводился парный `feedWindow`: дробный размер порции давал `limit 3.5`, а
  // отрицательный — `limit 0`, то есть вечно пустую ленту без единой ошибки.
  if (!Number.isInteger(perPage) || perPage <= 0) {
    throw new TypeError(`paging: perPage must be a positive integer, got ${typeof perPage}`)
  }
  return perPage + 1
}

/**
 * ССЫЛКА НА СЛЕДУЮЩУЮ ПОРЦИЮ — как `pageHref`, но параметром идёт курсор.
 *
 * Остальные параметры адреса переносятся (фильтры ленты не должны слетать на второй
 * порции), меняется ровно курсор. `null` — начало ленты, и тогда параметра нет вовсе:
 * у начала адрес ровно один, иначе поисковик видит два адреса с одним содержимым.
 */
export function cursorHref(
  pathname: string,
  params: URLSearchParams | Record<string, string | number | undefined | null>,
  param: FeedDirection = AFTER_PARAM,
): (cursor: string | null) => string {
  const qs = new URLSearchParams()
  const entries = params instanceof URLSearchParams ? [...params.entries()] : Object.entries(params)
  for (const [k, v] of entries) {
    // Выкидываются ОБА параметра курсора, а не только свой. Иначе шаг «назад» строился бы
    // поверх оставшегося `?after=`, адрес получал бы оба сразу, и страница читала бы тот,
    // что разбирает первым, — то есть шаг уводил бы не туда, куда написано на стрелке.
    if (CURSOR_PARAMS.includes(k) || v === undefined || v === null || v === '') continue
    qs.set(k, String(v))
  }
  return (cursor: string | null) => {
    const next = new URLSearchParams(qs)
    if (cursor) next.set(param, cursor)
    const s = next.toString()
    return s ? `${pathname}?${s}` : pathname
  }
}

/**
 * CANONICAL СТРАНИЦЫ ЛИСТАЛКИ — на СЕБЯ, а не на первую страницу.
 *
 * Страница 2 обязана канонизировать себя (`?page=2`), а не голый путь. Указать на
 * первую — значит сказать обходчику «весь этот список уже описан там», и тогда списки
 * со второй страницы и дальше не попадают в индекс вовсе: их канонический адрес
 * показывает другое содержимое. Так это и объясняют Google («не используйте первую
 * страницу как канонический адрес остальных») и Gitea/GitHub, где у страниц выдачи
 * canonical несёт собственный номер.
 *
 * Первая страница канонизируется БЕЗ параметра: `?page=1` и голый путь отдают одно и
 * то же, и параметр здесь только плодил бы второй адрес одной страницы.
 */
export function canonicalPage(pathname: string, page: number, param = PAGE_PARAM): string {
  // Через `pageHref`, а не своей строкой: правило «у первой страницы нет `?page=1`»
  // должно жить в ОДНОМ месте. Своя строка была вторым его владельцем — и, что хуже,
  // внутри файла, который узда дисциплины листания не проверяет (она смотрит страницы,
  // а не сам модуль). Разошлись бы они молча.
  return pageHref(pathname, {}, param)(page)
}

/**
 * Номер страницы ДЛЯ CANONICAL — из адреса, без верхней границы.
 *
 * Верхнюю знает только сама страница (она уже посчитала, сколько их всего), а
 * метаданные считаются раньше и отдельным проходом: повторять там счёт значило бы
 * второй запрос к базе на каждый показ ради краевого случая.
 *
 * ⚠️ ГРАНИЦА, названная вслух: `?page=999` при трёх страницах покажет третью, а
 * canonical назовёт 999-ю. Правильный ответ на такой адрес — 404 (так делают GitHub и
 * Gitea), и когда листалка начнёт его отдавать, расхождение исчезнет само. Пока — здесь
 * написано, что оно есть, чтобы следующий не решил, будто про этот случай не подумали.
 */
export function canonicalPageParam(raw: string | undefined): number {
  // ⚠️ ПОТОЛОК ОБЯЗАТЕЛЕН, и это не перестраховка. Свой разбор без него давал canonical
  // `?page=Infinity` на `?page=1e999` и `?page=1e+21` (с плюсом, который в адресе
  // означает пробел) на `?page=1e21`. `MAX_PAGE` заведён ровно против такого входа —
  // и разбор, повторяющий `pageFromParam` без его потолка, обходил защиту с той стороны,
  // где её никто не искал.
  return pageFromParam(raw, MAX_PAGE)
}

/**
 * Разбор сегмента адреса, который МОЖЕТ БЫТЬ ИСПОРЧЕН.
 *
 * `decodeURIComponent` бросает `URIError` на битой последовательности (`/mike/catalogs/100%`
 * — процент без двух цифр). В `generateMetadata` это исключение уходит наружу и страница
 * отвечает ПЯТИСОТКОЙ там, где правильный ответ — «не найдено»: сегмент просто не
 * соответствует ничему. Возвращаем сырую строку — дальше её всё равно не найдут в базе,
 * и путь придёт к штатному 404.
 */
export function decodeSegment(raw: string): string {
  try {
    return decodeURIComponent(raw)
  } catch {
    return raw
  }
}
