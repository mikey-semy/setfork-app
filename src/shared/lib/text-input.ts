/**
 * ПРИВЕДЕНИЕ ВХОДЯЩЕГО ТЕКСТА к канонической форме.
 *
 * Одна и та же русская буква записывается по-разному: «ё» — это либо один символ U+0451,
 * либо «е» плюс комбинирующие точки U+0308. Выглядят одинаково, но это разные строки:
 * поиск не находит, сравнение заголовков считает их разными, а человек правит вручную и
 * не понимает, что чинит. Владелец поймал это на списках, созданных через MCP.
 *
 * Источник расхождения — не наш код: составную форму отдают редакторы, буфер обмена macOS
 * и языковые модели. Поэтому нормализуем НА ВХОДЕ, в одной точке, а не ищем виноватого:
 * `NFC` — та самая каноническая композиция, которую W3C рекомендует как форму хранения
 * текста в вебе.
 *
 * Заодно убираем «мусорную невидимку», которая приезжает вместе с текстом из документов:
 * неразрывный пробел U+00A0 (ломает переносы и поиск по словам) и нулевой ширины U+200B–D,
 * который вообще не виден, но делает слова разными.
 */
const INVISIBLE = /[​-‍﻿]/g

export function normalizeText(raw: string): string {
  return raw.normalize('NFC').replace(INVISIBLE, '').replace(/ /g, ' ')
}

/** Нормализация + обрезка краёв — самый частый случай на входе формы или API. */
export function cleanText(raw: string | null | undefined): string {
  return normalizeText(raw ?? '').trim()
}
