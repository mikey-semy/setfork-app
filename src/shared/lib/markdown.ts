/**
 * Блок кода в Markdown, который НЕЛЬЗЯ закрыть изнутри.
 *
 * Экспортёр открывал фиксированное ограждение из трёх обратных кавычек, а команду
 * пишет автор списка. Достаточно поставить ` ``` ` внутрь команды — и всё, что
 * ниже, перестаёт быть кодом: следующие строки читаются как обычный Markdown, а в
 * рендерере с разрешённым HTML это уже сохранённый XSS. Минимум — скачанный
 * документ перестаёт соответствовать данным SetFork.
 *
 * По CommonMark (§4.5) закрывающее ограждение — строка не короче открывающего,
 * поэтому лекарство простое: открывать ограждением длиннее самой длинной цепочки
 * кавычек внутри. Тогда закрыть его содержимым невозможно в принципе — не нужно
 * ни экранировать, ни вырезать авторский текст.
 */
export function markdownCodeBlock(code: string, opts?: { indent?: string; lang?: string }): string[] {
  const indent = opts?.indent ?? ''
  // Переносы строк нормализуем: `\r` посреди Markdown ломает разметку так же,
  // как ломал исполняемый список (fe#663), и приходит он с любого Windows-клиента.
  const lines = code.replace(/\r\n?/g, '\n').split('\n')

  // Самая длинная цепочка кавычек в содержимом — где бы она ни стояла. Считаем не
  // только строки-ограждения: цепочка внутри строки закрывает блок ровно так же,
  // если открывающее ограждение оказалось короче.
  let longest = 0
  for (const line of lines) {
    for (const run of line.match(/`+/g) ?? []) longest = Math.max(longest, run.length)
  }
  const fence = '`'.repeat(Math.max(3, longest + 1))

  return [`${indent}${fence}${opts?.lang ?? ''}`, ...lines.map((l) => `${indent}${l}`), `${indent}${fence}`]
}
