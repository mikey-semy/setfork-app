/**
 * Куда вернуть человека после входа.
 *
 * ⚠️ ТОЛЬКО ВНУТРЕННИЙ ПУТЬ. Адрес приходит параметром, и без проверки это открытый
 * редирект: страница входа увела бы человека на чужой сайт с видом, будто он остался
 * у нас. Отвергаем всё, что не начинается с одиночного `/` — в том числе `//evil.com`,
 * который браузер читает как протокол-относительный АБСОЛЮТНЫЙ адрес.
 */
export function safeNext(raw: string | null | undefined, fallback = '/'): string {
  if (!raw) return fallback
  if (!raw.startsWith('/') || raw.startsWith('//') || raw.startsWith('/\\')) return fallback
  return raw
}
