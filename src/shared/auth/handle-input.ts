// Ввод ника человеком — ЧИСТЫЕ функции без БД и `crypto`, чтобы одно и то же правило
// работало и в браузере (поле ввода), и на сервере (экшены, поиск людей). Раньше
// каждое место снимало «@» своей регуляркой: соавторы — `/^@/` без нижнего регистра,
// перенос списка — `/^@+/` с ним, поиск людей не снимал вовсе. Итог — «@Mike» в одном
// поле находился, в другом нет.

/**
 * Ник так, как его набирают: ведущие «@» и пробелы вокруг — не часть ника
 * («@mike», « @ mike », «@@mike» → «mike»). Регистр НЕ трогаем — это правило для
 * поля под пальцем: человек видит ровно то, что набрал, минус служебный «@».
 */
export function stripHandleInput(raw: string): string {
  return raw.replace(/^[\s@]+/, '').trimEnd()
}

/** Нормализовать ввод ника для сверки с БД: то же снятие «@» + нижний регистр
 *  (ники хранятся строчными, см. HANDLE_RE). */
export function normalizeHandle(raw: string): string {
  return stripHandleInput(raw).toLowerCase()
}
