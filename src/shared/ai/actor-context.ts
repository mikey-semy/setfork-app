import { AsyncLocalStorage } from 'node:async_hooks'

/**
 * КТО ПОЗВАЛ МОДЕЛЬ — из КОНТЕКСТА ИСПОЛНЕНИЯ, а не из аргумента вызова.
 *
 * Журнал расхода пишут больше тридцати мест. Пометить их по одному значило бы завести
 * тридцать одну возможность забыть — а сегодняшний разбор долга ровно про это: шаг,
 * обязательный на каждом пути, живущий у вызывающих, однажды пропускается. Так уже было с
 * пере-проверкой модерации, с реестром тегов и с переиндексацией.
 *
 * Поэтому признак ставится ОДИН раз — там, где начинается работа компании: в диспетчере
 * петель (instrumentation). Всё, что позвано изнутри, помечается само; всё остальное
 * остаётся пользовательским.
 *
 * `AsyncLocalStorage` переживает `await` и не течёт между запросами: у каждого прохода петли
 * свой контекст, а веб-запрос его просто не имеет.
 */
type AiActor = 'user' | 'company'

const store = new AsyncLocalStorage<AiActor>()

/** Выполнить работу от имени КОМПАНИИ: всё, что внутри, пишется в журнал как её вызовы. */
export function runAsCompany<T>(fn: () => Promise<T>): Promise<T> {
  return store.run('company', fn)
}

/** Кем считать текущий вызов. Вне контекста петли — человеком. */
export function currentAiActor(): AiActor {
  return store.getStore() ?? 'user'
}
