// Зачистка «лесов рассуждения» из ответа модели.
//
// Ряд моделей (особенно RU) отвечают бланком: «Задача: … Метод: … Понимание: …
// План: … Выполнение: … Проверка: …». Пользователю нужен ОТВЕТ, а не протокол
// работы — это ровно та же граница, что «гномы не в тексте»: внутренняя кухня
// наружу не течёт. Промпт это запрещает, но модель мы не контролируем, поэтому
// на выходе стоит защитная зачистка.
//
// Убираем ТОЛЬКО ярлыки и служебные строки, содержимое сохраняем: иначе можно
// выбросить полезное. Строка вида «Проверка: убедиться, что объяснение понятно»
// — самооценка, её выкидываем целиком; «Выполнение:» с текстом после — оставляем
// текст.

/** Ярлыки-леса (рус/eng). Регистр не важен, двоеточие обязательно. */
const LABELS = [
  'задача',
  'метод',
  'понимание',
  'план',
  'выполнение',
  'решение',
  'ответ',
  'task',
  'method',
  'understanding',
  'plan',
  'execution',
  'answer',
]

/** Ярлыки, чьё содержимое — самооценка процесса, а не ответ: режем со строкой. */
const DROP_WHOLE = ['проверка', 'verification', 'self-check', 'самопроверка']

const labelRe = new RegExp(`^\\s*(?:\\*\\*|__)?(${LABELS.join('|')})(?:\\*\\*|__)?\\s*:\\s*`, 'i')
const dropRe = new RegExp(`^\\s*(?:\\*\\*|__)?(${DROP_WHOLE.join('|')})(?:\\*\\*|__)?\\s*:`, 'i')

/**
 * Ответ модели → человеческий текст без служебных заголовков.
 * Пустая строка на входе возвращается как есть (вызывающий сам решает).
 */
export function dehydrateScaffold(text: string): string {
  if (!text) return text
  const out: string[] = []
  for (const line of text.split('\n')) {
    if (dropRe.test(line)) continue // «Проверка: …» — отчёт о себе, не ответ
    const stripped = line.replace(labelRe, '')
    // Строка была ТОЛЬКО ярлыком («Выполнение:») — она ничего не несёт.
    if (stripped.trim() === '' && line.trim() !== '') {
      if (labelRe.test(line)) continue
    }
    out.push(stripped)
  }
  // Схлопываем пустые строки, оставшиеся от вырезанных ярлыков.
  return out
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}
