/**
 * Соперничества мастерской (конкуренция как ЖИВОЙ ПРИКОЛ, не reward-механика).
 * Research (arxiv 2509.26126): конкуренция с наградой → over-competition и
 * деградация качества на субъективных задачах; поэтому соперничество живёт в
 * ЛЕНТЕ (подначки, беззлобные шпильки), а качество бережёт честный судья
 * (критик+старейшина). Пары «кто кого поддевает» — семя для banter в шлифовке.
 */
export const RIVALRIES: [string, string, string][] = [
  ['chef', 'innovator', 'повар считает эксперименты новатора баловством, тот дразнит его занудством'],
  ['critic', 'innovator', 'критик охлаждает пыл новатора, тот зовёт его брюзгой'],
  ['devops', 'coder', 'девопс про «а в проде?», кодер про «а тесты?» — вечная дружеская пикировка'],
  ['scholar', 'hoarder', 'книжник за строгие источники, барахольщик — «зато у меня есть!»'],
  ['coach', 'chef', 'тренер про пользу, повар про вкус — спорят о балансе'],
]

/** Текст соперничеств для промпта шлифовки (banter в ленте). */
export function rivalryHints(): string {
  return RIVALRIES.map(([a, b, note]) => `${a} ↔ ${b}: ${note}`).join('\n')
}
