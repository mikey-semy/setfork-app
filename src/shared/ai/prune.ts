/**
 * КОНТЕКСТ-ПРУННИНГ на рёбрах совета — единственный оставшийся рычаг цены.
 *
 * Черновики уходят в промпт ДВАЖДЫ: критику («разбери их») и старейшине («сведи их»). При
 * четырёх участниках это четыре текста, оплаченных два раза, и растут они бесконтрольно —
 * модель, которую попросили «6-9 пунктов с пояснением», иногда пишет полотно.
 *
 * Что здесь СОЗНАТЕЛЬНО не делается:
 *   - не выбрасываем черновики у старейшины (он сводит из них, а не из пересказа критика);
 *   - не схлопываем «общее» в один блок: критика прямо спрашивают, чей шаг сильнее, и без
 *     привязки к букве этот вопрос теряет смысл;
 *   - не режем середину текста. Обрезка идёт по ГРАНИЦЕ СТРОКИ: половина пункта хуже, чем
 *     его отсутствие — модель достроит обрубок и будет спорить с тем, чего никто не писал.
 *
 * То есть это подрезка выбросов, а не сжатие: типичный черновик не трогается вовсе. Сколько
 * реально сэкономлено — считается и уезжает в провенанс, чтобы эффект был числом, а не верой
 * в то, что «фаза ревью съедает 60% токенов».
 */

/** Потолок на черновик в анонимном блоке. Типичный черновик (6-9 пунктов) сильно меньше. */
export const DRAFT_CHAR_CAP = 2200

/** Пометка обрезки — видна и модели, и человеку в журнале. */
const CUT_MARK = '…[обрезано]'

export interface PruneStat {
  /** Символов до подрезки. */
  before: number
  /** Символов после. */
  after: number
  /** Сколько черновиков реально подрезано (обычно 0). */
  trimmed: number
}

/**
 * Подрезать текст по границе строки, не превышая потолок. Возвращает исходный текст, если он
 * и так укладывается: подрезка не должна оставлять след там, где её не было.
 */
export function trimToLines(text: string, cap = DRAFT_CHAR_CAP): string {
  const t = text.trim()
  if (t.length <= cap) return t
  const lines = t.split('\n')
  const kept: string[] = []
  let len = 0
  for (const line of lines) {
    // +1 на перевод строки; резерв под пометку, чтобы итог не вылез за потолок.
    const next = len + line.length + 1
    if (next > cap - CUT_MARK.length - 1) break
    kept.push(line)
    len = next
  }
  // Ни одна строка не влезла (одна гигантская строка) — режем её жёстко, иначе вернём пустоту.
  // Минус перевод строки перед пометкой: он тоже символ, и без него итог вылезал за потолок.
  if (!kept.length) return t.slice(0, cap - CUT_MARK.length - 1).trimEnd() + '\n' + CUT_MARK
  return kept.join('\n').trimEnd() + '\n' + CUT_MARK
}

/** Подрезка набора черновиков + честная статистика экономии. */
export function pruneDrafts<T extends { text: string }>(drafts: T[], cap = DRAFT_CHAR_CAP): { drafts: T[]; stat: PruneStat } {
  let before = 0
  let after = 0
  let trimmed = 0
  const out = drafts.map((d) => {
    const text = trimToLines(d.text, cap)
    before += d.text.trim().length
    after += text.length
    if (text !== d.text.trim()) trimmed++
    return { ...d, text }
  })
  return { drafts: out, stat: { before, after, trimmed } }
}
