import { CopyButton } from './CopyButton'
import { highlightLines } from './highlight-code'
import { TEXT } from './control'
import type { Lang } from '@/shared/i18n'

/**
 * Карточка кода для ЧТЕНИЯ (не редактор): подсветка синтаксиса, номера строк,
 * перенос длинных строк вместо горизонтального скролла (правило владельца: код в
 * своей форме, скролла нет).
 *
 * БЕЗ ПОЛОСЫ-ШАПКИ. Отдельная строка с именем и кнопкой съедала около 28px над
 * каждым блоком, а несла всего два служебных элемента — на телефоне это заметная
 * часть экрана (жалоба владельца 04.08.2026). Язык и «копировать» висят в правом
 * верхнем углу самой карточки, там же, где остальные служебные действия.
 *
 * ⚠️ ОТСТУП ПОД УГОЛ — У ВСЕХ СТРОК ОДИНАКОВЫЙ. Раньше его получала только первая:
 * экономия места вышла дороже, чем казалась. Строка 1 переносилась там, где строки
 * 2 и 3 такой же длины помещались целиком, — перенос выглядел случайным, а главное
 * ломалось ВЫРАВНИВАНИЕ: в коде колонки («состояние → результат») несут смысл, и
 * рваная первая строка его убивает. Жалоба владельца со снимка 01.09.2026.
 *
 * Плата за одинаковый отступ снижена вдвое: бейдж языка на узком экране скрыт. Он
 * служебный, подсветка и так показывает, что это код, — а на телефоне он стоил
 * ровно тех 60px, из-за которых отступ и жалели.
 *
 * Подсветка построчная (highlight-code): токены раскладываются по строкам, поэтому
 * номера и перенос сохраняются — готовый HTML от highlight.js так резать нельзя.
 * Язык берём из `name`: он приходит из ограды markdown или от детектора.
 */
export function CodeCard({ code, name, lang }: { code: string; name?: string; lang?: Lang }) {
  const label = name || 'code'
  const lines = highlightLines(code, name)
  // Минимальная высота карточки — под служебный угол, а не под текст: блок из ОДНОЙ
  // строки занимает ~37px, а кнопка копирования на тач-экране 44px, и угол выпирал за
  // низ карточки (жалоба владельца 04.08.2026). Уменьшать кнопку нельзя — 44px это
  // норма тач-цели, поэтому карточка просто не бывает ниже своего угла.
  return (
    <div className="sf-code-card relative my-1.5 min-h-10 overflow-hidden rounded-md border border-border bg-surface-2 pointer-coarse:min-h-13">
      {/* Правый верхний угол — служебное (правило углов). Подложка у бейджа на случай,
          если первая строка всё же окажется длинной и пройдёт под ним. */}
      <div className="absolute right-1 top-1 z-10 flex items-center gap-1 print:hidden">
        {/* Бейдж только там, где есть место: на 390px он отнимал у КАЖДОЙ строки
            больше, чем сообщал. */}
        <span
          className={`hidden rounded bg-surface-2/85 px-1.5 py-0.5 font-mono sm:inline ${TEXT.caption} uppercase tracking-wide text-muted`}
        >
          {label}
        </span>
        <CopyButton text={code} lang={lang} />
      </div>
      <div className="py-2 font-mono text-body-sm leading-[1.55] text-ink">
        {lines.map((tokens, i) => (
          // Отступ одинаков у всех строк: под кнопку (тач-цель) на узком экране и под
          // кнопку с бейджем на широком. Разный отступ рвал выравнивание — см. шапку.
          // На печати угол скрыт (`print:hidden` выше), поэтому и место под него не
          // резервируем: иначе бумага теряла бы 104px справа и рвала КАЖДУЮ строку.
          <div key={i} className="flex gap-2 px-2.5 pr-11 sm:pr-26 print:pr-2.5">
            {/* ⚠️ НОМЕРА СТРОК — НЕ НА ТЕЛЕФОНЕ. Они стоят 28px у каждой строки, а
                сослаться на строку в списке нельзя и выделить её отдельно тоже: это
                украшение, за которое на 390px платит сам код. На печати и на широком
                экране номера остаются — там место есть, а на бумаге они и нужны. */}
            <span className="hidden w-5 shrink-0 select-none text-right text-caption leading-[1.7] text-muted sm:inline-block print:inline-block">
              {i + 1}
            </span>
            <span className="min-w-0 whitespace-pre-wrap [overflow-wrap:anywhere]">
              {tokens.length === 0 ? ' ' : tokens.map((t, j) => (t.cls ? <span key={j} className={t.cls}>{t.text}</span> : <span key={j}>{t.text}</span>))}
            </span>
          </div>
        ))}
      </div>
    </div>
  )
}
