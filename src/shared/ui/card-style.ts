import { cn } from '@/shared/lib/cn'

/**
 * КАРТОЧКА — рамка + фон + внутренний отступ. Один рецепт на всё приложение.
 *
 * Замер 13.08.2026 (Ф13 трека ui-system): примитива под эту роль не было ВОВСЕ,
 * поэтому её писали руками — 35 разных рецептов в 94 местах, из них семь
 * внутренних отступов на одну и ту же роль (p-3, p-3.5, p-4, p-5, p-6, p-8, p-1).
 * Это и есть «везде по-разному», которое видно первым же взглядом.
 *
 * Вид живёт ОТДЕЛЬНО от разметки (как buttonClass рядом): карточка — это чаще
 * всего `div` со своими классами раскладки (`mb-4`, `flex`, `space-y-2`), и
 * навязывать ей компонент значило бы либо плодить пропы под каждый случай, либо
 * заставлять оборачивать. Функция даёт рецепт, вызывающий добавляет раскладку.
 *
 * Панели и секции сюда НЕ входят: у окна (OverlayPanel/PickerPanel) и секции
 * настроек (SettingsSection) своя анатомия с шапкой и футером — это другая роль.
 */

/** Тон = смысл блока, а не цвет. Обычная карточка, вложенный блок, состояние. */
export type CardTone = 'surface' | 'inset' | 'accent' | 'ok' | 'warn' | 'danger'

/**
 * Внутренний отступ. Четыре ступени вместо одиннадцати; мэппинг взят ИЗ ЗАМЕРА,
 * а не назначен заново:
 *   xs (4px)  — контейнер списка: зазор, чтобы подсветка строки не липла к рамке
 *               (было p-0.5/p-1/p-1.5);
 *   sm (12px) — плотный блок, вложенные карточки (было p-2/p-2.5/p-3);
 *   md (16px) — СТАНДАРТ, самый частый случай (было p-3.5/p-4);
 *   lg (24px) — просторная: пустое состояние, герой (было p-5/p-6/p-8).
 */
export type CardPad = 'none' | 'xs' | 'sm' | 'md' | 'lg'

const TONE: Record<CardTone, string> = {
  surface: 'border-border bg-surface',
  // Вложенный блок внутри карточки/панели: на тон глубже, радиус меньше.
  inset: 'border-border bg-surface-2',
  accent: 'border-(--accent)/40 bg-(--accent-soft)',
  ok: 'border-ok/50 bg-ok/10',
  warn: 'border-warn/50 bg-warn/10',
  danger: 'border-danger/40 bg-danger/5',
}

const PAD: Record<CardPad, string> = {
  none: '',
  xs: 'p-1',
  sm: 'p-3',
  md: 'p-4',
  lg: 'p-6',
}

export function cardClass({
  tone = 'surface',
  pad = 'md',
  dashed = false,
  className,
}: {
  tone?: CardTone
  pad?: CardPad
  /** Пустышка или зона перетаскивания: та же карточка, но рамка пунктиром. */
  dashed?: boolean
  className?: string
} = {}): string {
  return cn(
    // Радиус — по роли: у самостоятельной карточки крупнее, у вложенной мельче.
    // Это единственное место, где решение записано, и потому единственное,
    // которое надо править, если оно изменится.
    'border',
    tone === 'inset' ? 'rounded-md' : 'rounded-lg',
    TONE[tone],
    PAD[pad],
    dashed && 'border-dashed',
    className,
  )
}
