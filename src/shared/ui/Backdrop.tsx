'use client'

import { cn } from '@/shared/lib/cn'
import { LAYER } from './control'

/**
 * ПОДЛОЖКА под всплывающим: ловит клик мимо и (когда нужно) притеняет страницу.
 *
 * Замер 27.08.2026: своя подложка была написана пять раз — в меню на якоре, в окне
 * поверх, в шторке, в боковой панели и в выборе ветки. Разошлись обе величины, из
 * которых она состоит: притенение писали тремя значениями (`bg-black/30`, `/40`,
 * `/50`), слой — четырьмя (`z-10`, `z-40`, `z-50`, `LAYER.overlay`), хотя лестница
 * слоёв в проекте есть с 13.08. То есть подложка меню могла оказаться ВЫШЕ шторки.
 *
 * Два вида, и разница между ними смысловая, а не цветовая:
 *  • `dim` — страница уходит на задний план, содержимое требует внимания (шторка,
 *    модалка, боковая панель на телефоне);
 *  • без `dim` — прозрачная ловушка клика: меню или список ветки должны закрываться
 *    щелчком мимо, но страницу под собой не глушат. Так это сделано у GitHub.
 *
 * Для диктора подложки НЕТ (`aria-hidden`), и это осознанно: объявлять пустой
 * элемент поверх содержимого незачем, а закрыть всплывающее с клавиатуры можно
 * Escape'ом — за него отвечает сама панель, не подложка.
 */
/**
 * Притенение — ОДНО значение на приложение. Было три (`/30` у окна поверх, `/40` у
 * боковой панели, `/50` у шторки), то есть одно и то же действие — «убрать страницу
 * на задний план» — выглядело по-разному в зависимости от того, кто его писал.
 *
 * Вынесено константой, а не спрятано внутрь компонента, потому что двум подложкам он
 * не подходит по устройству: у окна поверх подложка `absolute` внутри своей обоймы
 * (иначе легла бы ПОВЕРХ окна), у шторки её рисует Radix своим элементом.
 */
export const BACKDROP_DIM = 'bg-black/40'

export function Backdrop({
  onClose,
  dim = false,
  layer = 'overlay',
  className,
}: {
  onClose: () => void
  dim?: boolean
  /** Ступень лестницы слоёв. Подложка обязана лежать ПОД своей панелью и НАД страницей. */
  layer?: keyof typeof LAYER
  className?: string
}) {
  return (
    <div
      aria-hidden
      onClick={onClose}
      className={cn('fixed inset-0', LAYER[layer], dim && `animate-sf-fade ${BACKDROP_DIM}`, className)}
    />
  )
}
