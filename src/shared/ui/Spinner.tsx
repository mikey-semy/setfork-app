import { Loader2 } from 'lucide-react'
import { cn } from '@/shared/lib/cn'
import { iconSizeFor, type ControlSize } from './control'

/**
 * Ожидание: крутящийся кружок внутри кнопки, панели или строки.
 *
 * Заведён 26.08.2026 по замеру `scripts/ui-parity.mjs`: роль была самой массовой из
 * переоткрытых руками — 60 мест в 44 файлах, и примитива под неё не существовало
 * вовсе. Писали её всегда одинаково (`<Loader2 className="animate-spin" />`) и всегда
 * по-разному: восемь размеров — 12, 13, 14, 15, 16, 17, 18 и один честный
 * `iconSizeFor('sm')`. То есть лестница иконок в проекте была, а половина ожиданий
 * шла мимо неё.
 *
 * Размер берётся от КОНТРОЛА, рядом с которым стоит кружок (`size` — та же ступень,
 * что у кнопки или поля), а не подбирается на глаз.
 *
 * Доступность разведена по двум случаям, потому что они противоположны:
 *  • кружок ВНУТРИ кнопки заменяет её значок — читалке он не нужен, подпись кнопки
 *    уже сказала, что происходит: по умолчанию `aria-hidden`;
 *  • кружок САМ ПО СЕБЕ (панель грузится, список обновляется) — единственное, что
 *    сообщает о работе: тогда передают `label`, и он объявляется как `role="status"`.
 */
export function Spinner({
  size = 'md',
  label,
  className,
}: {
  size?: ControlSize
  /** Задан — кружок объявляет ожидание сам (`role="status"`). Внутри кнопки не нужен. */
  label?: string
  className?: string
}) {
  return (
    <Loader2
      size={iconSizeFor(size)}
      className={cn('shrink-0 animate-spin', className)}
      {...(label ? { role: 'status', 'aria-label': label } : { 'aria-hidden': true })}
    />
  )
}
