import { cn } from '@/shared/lib/cn'

/**
 * КОМАНДА ШАГА — ОДИН СПОСОБ ПОКАЗА НА ВЕСЬ ПРОДУКТ.
 *
 * Одно и то же поле `step.command` рисовалось ШЕСТЬЮ разметками с несовместимым
 * поведением: где-то перенос по словам, где-то прокрутка, где-то голый `<code>` вообще
 * без классов, где-то обрезка. Отсюда жалоба владельца «на мобильном код переносится,
 * хотя мы это исправляли» — исправляли в одном месте из шести.
 *
 * ⚠️ ПОВЕДЕНИЕ: ПРОКРУТКА, А НЕ ПЕРЕНОС. Команду рвут по словам только там, где
 * прокрутки нет физически (печать). На экране перенос опаснее: перенесённая строка
 * читается как две команды, а скопированный кусок ломается. Так же показывают команды
 * GitHub и Gitea. Прокрутка живёт ВНУТРИ блока (`min-w-0` + `overflow-x-auto`), поэтому
 * страницу вбок не растягивает — правило мобильной вёрстки про отсутствие
 * горизонтального скролла относится к странице, а не к блоку кода.
 *
 * ⚠️ ВЫСОТА — ПО СОДЕРЖИМОМУ, И ЭТО НЕ МЕЛОЧЬ. Однострочная команда занимает строку,
 * многострочная — столько, сколько в ней строк. Фиксированная ступень (`h-8`, как у
 * контролов) показывала бы многострочный скрипт одной строкой с невидимыми переносами:
 * человек копирует и получает не то, что видел.
 *
 * Печать не использует этот компонент: там `CodeCard` с переносом и номерами строк —
 * названное исключение, а не забытое место.
 *
 * ⚠️ ПРОКРУЧИВАЕМЫЙ БЛОК ОБЯЗАН БЫТЬ ДОСТИЖИМ КЛАВИАТУРОЙ. Спрятанный вправо текст
 * иначе недоступен без мыши (WCAG 2.1.1): Chrome сам делает прокручиваемые области
 * фокусируемыми, Firefox и Safari — нет, поэтому `tabIndex` проставлен явно. Так же
 * сделано у GitHub (`<pre tabindex="0">`).
 *
 * ⚠️ ПОЛОСА ПРОКРУТКИ ВИДНА ПО УМОЛЧАНИЮ — это единственный признак, что строка
 * продолжается. Прятать её позволено там, где текст целиком забирает соседняя кнопка
 * копирования и где высота зажата ступенью шкалы (`CopyRow` передаёт `no-scrollbar`):
 * классическая полоса Windows съела бы там половину строки.
 */
export function CommandText({ value, className }: { value: string; className?: string }) {
  return (
    <code
      // Правило считает элемент неинтерактивным и не знает про прокрутку: спрятанный
      // вправо текст без фокуса недоступен без мыши (WCAG 2.1.1). Так же сделано у
      // GitHub (<pre tabindex="0">). Подавление одно на продукт — здесь, а не в
      // каждом месте показа.
      // eslint-disable-next-line jsx-a11y/no-noninteractive-tabindex
      tabIndex={0}
      className={cn(
        'block min-w-0 select-text overflow-x-auto whitespace-pre font-mono outline-offset-2',
        className,
      )}
    >
      {value}
    </code>
  )
}
