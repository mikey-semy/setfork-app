'use client'

import type { ReactNode } from 'react'
import { useViewportBottom } from './use-viewport-bottom'

/**
 * ГЛАВНОЕ ДЕЙСТВИЕ ФОРМЫ — у большого пальца, а не в конце простыни.
 *
 * Решение владельца 09.08.2026, принятое для создания списка: «на длинном списке кнопка
 * в конце формы уезжает за экран, и до неё надо доскроллить». В правке существующего
 * списка кнопки так и остались последней строкой — а правят как раз длинные списки.
 * 22.09.2026 владелец сообщил, чем это кончается на списке в 120 пунктов: до конца он
 * добраться не смог вовсе.
 *
 * Поэтому панель общая, а не третья копия `fixed right-5 bottom-5` на каждой странице:
 * правило «главное действие видно с любого места формы» должно жить в ОДНОМ месте,
 * иначе четвёртая страница с редактором про него не узнает — так и вышло с правкой.
 * Узда `tests/architecture/editor-floating-actions.test.ts` этого больше не позволит.
 *
 * Почему не `FormSaveBar`: та показывается только когда форму тронули. Здесь так нельзя —
 * черновик, сохранённый вчера, нужно уметь опубликовать сегодня, не изменив ни буквы.
 *
 * Слева внизу живёт плавающий «назад» (`FloatingBack`), справа — эта панель; между ними
 * центр остаётся свободным под инсертер блоков.
 */
export function FloatingActions({ children }: { children: ReactNode }) {
  // ⚠️ bottom от ВИДИМОГО низа. `position: fixed; bottom: N` считает низ от layout
  // viewport, а человек видит visual viewport: на мобиле панели браузера и клавиатура
  // их расходят, и «прижатая к низу» панель честно сидит внизу СТРАНИЦЫ, а на экране
  // висит посередине. Это уже было жалобой владельца 03.08.2026 про чат и «наверх»;
  // в странице создания поправку не применили, и там кнопка вела себя так же.
  const { gap } = useViewportBottom()
  return (
    <div
      // `data-sticky-input` — общий признак нижней плавающей панели: по нему кнопка
      // «наверх» садится ВЫШЕ неё, а не поверх (механика ScrollToTop).
      data-sticky-input
      style={gap ? { bottom: gap + 20 } : undefined}
      className={`fixed right-5 z-40 flex items-center gap-2 print:hidden ${gap ? '' : 'bottom-5'}`}
    >
      {children}
    </div>
  )
}
