import type { Metadata } from 'next'
import type { Lang } from '@/shared/i18n'
import { langAlternates, langHref } from '@/shared/i18n/url'

/** Общесайтовая карточка ссылки: 1200×630, лежит в `public/`. */
export const SITE_OG_IMAGE = '/og-image.png'

/**
 * МЕТАДАННЫЕ СТРАНИЦЫ, ВКЛЮЧАЯ КАРТОЧКУ ССЫЛКИ.
 *
 * ⚠️ NEXT СЛИВАЕТ МЕТАДАННЫЕ ПОВЕРХНОСТНО. Сегмент, объявивший `title`, но не
 * объявивший `openGraph`, наследует родительский `openGraph` ЦЕЛИКОМ — вместе с чужим
 * заголовком и описанием. На экране страница называется правильно, а в мессенджере
 * разворачивается как ссылка на главную: «SetFork — versioned, runnable lists».
 *
 * Замер на проде 03.09.2026: `/changelog`, `/explore`, `/tags`, `/trending`, страницы
 * задач и версий любого списка — у всех карточка была общесайтовой. У самих списков её
 * починили точечно ещё 28.08, и комментарий там объясняет ровно это; но правило осталось
 * в одном файле, поэтому все остальные страницы продолжали наследовать чужую карточку.
 *
 * Поэтому здесь функция, а не памятка: заголовок и описание задаются ОДИН раз и
 * расходятся во все три места — вкладку браузера, карточку OpenGraph и карточку Twitter.
 *
 * ⚠️ ЯЗЫК КАРТОЧКИ — ЯЗЫК ОТВЕТА. Предпросмотрщик мессенджера не присылает
 * `Accept-Language` никогда, поэтому карточка у него всегда на языке по умолчанию. Это не
 * дефект функции: вызывающий передаёт уже переведённые строки, и если однажды мы решим
 * отдавать ботам другой язык, менять придётся согласование языка, а не это место.
 */
export function pageMeta(o: {
  /** Заголовок страницы. Шаблон корня добавит « · SetFork» во вкладке. */
  title: string
  description?: string
  /** Путь для canonical и `og:url`. Без него ссылки не переписываем. */
  path?: string
  /**
   * Своя картинка карточки. По умолчанию — общесайтовая `/og-image.png`.
   *
   * ⚠️ Раньше здесь стояло «по умолчанию — общесайтовая из корневого layout», и это было
   * НЕВЕРНО ровно по той причине, которую объясняет докблок выше: Next сливает метаданные
   * поверхностно, и `openGraph`, объявленный здесь, замещает родительский ЦЕЛИКОМ —
   * вместе с картинкой. Замер прода 22.09.2026: `og:image` и `twitter:image` на главной
   * отсутствовали вовсе, при том что в корневом макете они заданы.
   *
   * Цена — не косметика: каждая ссылка на SetFork в мессенджере разворачивалась серым
   * прямоугольником, а продукт распространяется именно ссылками между разработчиками.
   */
  image?: string
  /** Страница не для индекса (личные разделы, служебные экраны). */
  noindex?: boolean
  /**
   * Язык страницы. Без него `canonical` указывает на адрес БЕЗ префикса, и русская
   * страница объявляет себя копией общей — для поисковика это «не индексировать».
   * Языки разведены по адресам 22.09.2026, потому что YandexBot не шлёт
   * `Accept-Language` и русской версии в индексе не существовало вовсе.
   */
  lang?: Lang
}): Metadata {
  const { title, description, path, image, noindex, lang } = o
  // Картинка есть ВСЕГДА: своя или общесайтовая. Унаследовать её от макета нельзя —
  // см. предупреждение о поверхностном слиянии выше.
  const images = [{ url: image ?? SITE_OG_IMAGE }]
  // ОДИН адрес страницы на канон и на карточку соцсетей. Когда они расходились, карточка
  // `/ru/explore` называла себя `/explore`: соцсеть склеивала её с версией без языка, и
  // получатель ссылки попадал на язык своего браузера, а не на тот, которым поделились
  // (находка авто-ревью к SEO-1).
  const canonical = path ? (lang ? langHref(path, lang) : path) : undefined
  return {
    title,
    ...(description ? { description } : {}),
    // ⚠️ Ссылки на языковые версии — ЗДЕСЬ, а не в корневом макете: метаданные страницы
    // замещают одноимённое поле целиком, и `alternates` из макета до готовой страницы не
    // доезжают. Проверено живым запросом: `hreflang` не было ни одного, пока помощник
    // молчал о языках.
    ...(path
      ? {
          alternates: {
            canonical,
            languages: { ...langAlternates(path).languages, 'x-default': path },
          },
        }
      : {}),
    ...(noindex ? { robots: { index: false, follow: false } } : {}),
    openGraph: {
      type: 'website',
      siteName: 'SetFork',
      title,
      ...(description ? { description } : {}),
      ...(canonical ? { url: canonical } : {}),
      images,
    },
    twitter: {
      card: 'summary_large_image',
      title,
      ...(description ? { description } : {}),
      images,
    },
  }
}
