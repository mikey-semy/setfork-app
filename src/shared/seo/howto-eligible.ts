/**
 * ОБЪЯВЛЯТЬ ЛИ СТРАНИЦУ СПИСКА ИНСТРУКЦИЕЙ (`HowTo`) — одно правило, проверяемое тестом.
 *
 * Содержимое SetFork совпадает с этой схемой один в один: шаги по порядку, у каждого
 * название и пояснение. Большинству сайтов её приходится натягивать на сплошной текст,
 * а здесь она описывает ровно то, что есть (аудит 22.09.2026 называет это редким
 * совпадением, которое стоит занять первым). Но разметка, сказавшая больше, чем на
 * странице есть, хуже отсутствующей: поисковик покажет шаг, которого нет. Отсюда условия —
 * все, кроме последнего, найдены авто-ревью по одному:
 *
 *  • УПОРЯДОЧЕННЫЙ. У неупорядоченного списка порядка нет, «шаг 1 из 12» — враньё.
 *  • ТИП «процедура». Инвентарь, чеклист, критерии, варианты и рецепт тоже хранятся
 *    упорядоченными, но их пункты — вещи и утверждения: «шаг 3: мука 400 г». Пустой тип
 *    читается как процедура, как и везде в проекте (`list-kind.ts`).
 *  • НЕ АЛЬТЕРНАТИВНЫЙ ВИД. На `?v=N` и `?ref=…` показана старая версия или ветка, а
 *    разметка приписала бы эти шаги каноническому адресу.
 *  • НЕ ОТФИЛЬТРОВАННЫЙ ВИД. На `?find=…` шаги — только совпавшие: под каноном легла бы
 *    неполная, перенумерованная инструкция.
 *  • НИЧЕГО НЕ ЗАПЕРТО. У курса с тестами ученик не видит уроков дальше несданного, а
 *    разметка выложила бы их текст в исходник его же страницы. Поисковик приходит без
 *    входа, запирание его не касается — индекс не теряет ничего.
 *  • ЕСТЬ ХОТЬ ОДИН ШАГ. Список из одних текстов и картинок инструкцией не является.
 */
export function howToEligible(o: {
  ordered: boolean
  listKind: string | null | undefined
  readOnlyView: boolean
  find: string
  firstLockedIdx: number
  stepCount: number
}): boolean {
  return (
    o.ordered &&
    (o.listKind ?? 'procedure') === 'procedure' &&
    !o.readOnlyView &&
    !o.find &&
    o.firstLockedIdx < 0 &&
    o.stepCount > 0
  )
}
