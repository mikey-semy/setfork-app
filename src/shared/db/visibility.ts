import { and, eq, type SQL } from 'drizzle-orm'
import { templates } from './schema'

/**
 * «Список виден кому угодно» — ОДНО определение для всех запросов.
 *
 * Условие из трёх частей (опубликован, публичный, не снят модерацией) было
 * скопировано в дюжину мест: витрина, поиск, задачи, рудник знаний, обходчик ссылок,
 * садовник, статистика гномов, backlinks на странице списка. Копии живут, пока
 * определение не меняется, — а оно меняется: появись завтра ещё одно состояние
 * модерации или архив, часть запросов узнала бы о нём, а часть продолжила отдавать
 * скрытое. Промах здесь стоит дорого: это утечка чужого содержимого наружу.
 *
 * Ровно то же правило для ОДНОГО списка (с учётом зрителя и коллаборантов) живёт в
 * `canViewList` (core): там решают про конкретную запись, здесь фильтруют выборку.
 */
export function publiclyVisible(): SQL {
  return and(eq(templates.status, 'published'), eq(templates.visibility, 'public'), eq(templates.moderation, 'active'))!
}
