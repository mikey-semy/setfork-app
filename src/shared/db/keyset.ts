import 'server-only'
import { sql, type Column, type SQL } from 'drizzle-orm'
import type { Cursor } from '@/shared/lib/paging'

/**
 * KEYSET НА УРОВНЕ ЗАПРОСА — три кусочка, из которых собирается пополняемая лента.
 *
 * Кодирование курсора живёт в `shared/lib/paging` (оно нужно и разметке, и адресам, и
 * клиенту), а здесь то, что без drizzle не выражается: порядок, условие «строго после»
 * и колонка ключа полной точности.
 *
 * Почему именно так, а не «offset побыстрее»: смещение считается ОТ НАЧАЛА выдачи, и на
 * ленте это начало сдвигается прямо во время чтения. Подробности — в `shared/lib/paging`
 * (раздел keyset) и в треке пагинации; здесь достаточно правила: строки, читаемые сверху
 * вниз и пополняемые сверху, листаются ключом.
 */

/**
 * ПОРЯДОК ДЛЯ KEYSET: оба ключа вниз.
 *
 * Это НЕ описка и не расхождение с остальным сайтом, где доопределение идёт `asc(id)`.
 * Условие «строго после» ниже — построчное сравнение кортежей `(key, id) < (:key, :id)`,
 * а оно осмысленно ТОЛЬКО когда обе колонки упорядочены в одну сторону. Смешанный
 * порядок (`key desc, id asc`) кортежным сравнением не выражается вовсе: пришлось бы
 * писать `key < :key or (key = :key and id > :id)`, и такая форма уже не ложится на
 * составной индекс одним диапазонным сканом — ради чего keyset и заводился.
 *
 * Под это нужен индекс `(… , key DESC, id DESC)`. Оба `DESC` — с `NULLS FIRST`, иначе
 * индекс не совпадёт с `ORDER BY` и порядок он не отдаст (см. грабли трека и
 * `tests/architecture/index-nulls-order`).
 */
export function keysetOrder(key: Column, id: Column): SQL[] {
  return [sql`${key} desc`, sql`${id} desc`]
}

/**
 * КЛЮЧ КУРСОРА ТЕКСТОМ — колонка, из которой строится курсор следующей порции.
 *
 * Брать типизированное значение колонки НЕЛЬЗЯ: `timestamptz` в Postgres хранит
 * микросекунды, а `Date` в JS — миллисекунды, и drizzle отдаёт колонку уже обрезанной
 * (замер 18.08: в базе `19:02:03.092835`, в приложении `19:02:03.092Z`). Курсор из
 * обрезанного ключа отсекает вместе с показанным и всё, что попало в отброшенные
 * микросекунды, — строки исчезают молча, то есть keyset начинает делать ровно то, ради
 * избавления от чего его и вводят.
 */
export function cursorKey(key: Column): SQL<string> {
  return sql<string>`${key}::text`
}

/**
 * УСЛОВИЕ «СТРОГО ПОСЛЕ КУРСОРА» для порядка `keysetOrder`.
 *
 * `undefined` при `null`-курсоре — это начало ленты: условия нет, и вызывающий кладёт
 * результат прямо в `and(...)`, где `undefined` игнорируется. Отдельной ветки «если
 * первая порция» на каждой поверхности из-за этого не заводится.
 *
 * Ключ уходит параметром с явным приведением: он приехал из адреса, и хотя проверен
 * `decodeCursor` до формы `timestamptz`, приведение здесь — не дубль проверки, а
 * ЕДИНСТВЕННОЕ место, где база узнаёт тип. Без него Postgres сравнивал бы `timestamptz`
 * с `text` и падал бы на несуществующем операторе.
 */
export function afterCursor(key: Column, id: Column, cursor: Cursor | null): SQL | undefined {
  if (!cursor) return undefined
  return sql`(${key}, ${id}) < (${cursor.key}::timestamptz, ${cursor.id}::uuid)`
}
