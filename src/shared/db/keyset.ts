import 'server-only'
import { sql, type Column, type SQL } from 'drizzle-orm'
import type { Cursor, CursorKeyType, FeedDirection, FeedOrder } from '@/shared/lib/paging'

/**
 * KEYSET НА УРОВНЕ ЗАПРОСА — два кусочка, из которых собирается пополняемая лента.
 *
 * Кодирование курсора живёт в `shared/lib/paging` (оно нужно и разметке, и адресам, и
 * клиенту), а здесь то, что без drizzle не выражается: шаг (условие + порядок) и колонка
 * ключа полной точности.
 *
 * Почему именно так, а не «offset побыстрее»: смещение считается ОТ НАЧАЛА выдачи, и на
 * ленте это начало сдвигается прямо во время чтения. Подробности — в `shared/lib/paging`
 * (раздел keyset) и в треке пагинации; здесь достаточно правила: строки, читаемые сверху
 * вниз и пополняемые сверху, листаются ключом.
 */

/**
 * ШАГ KEYSET ЦЕЛИКОМ: условие и порядок ОДНОЙ сущностью.
 *
 * Порознь их отдавать нельзя, и это не стилистика. Условие и порядок обязаны смотреть в
 * одну сторону: `<` идёт с `desc`, `>` — с `asc`. Разъехались — и запрос возвращает не
 * соседнюю порцию, а хвост ленты с другого конца, причём молча и правдоподобно. Две
 * отдельные функции позволяли бы задать им разные направления; одна — нет.
 *
 * ДВА РАЗНЫХ ПОНЯТИЯ, которые легко перепутать и которые здесь разведены:
 *
 *   `order` — как лента ПОКАЗЫВАЕТСЯ. `desc` — свежее сверху (уведомления, активность);
 *             `asc` — старое сверху (тред обсуждения: его читают с начала, а дописывают
 *             в конец).
 *   `dir`   — куда ШАГАЮТ ОТНОСИТЕЛЬНО ЧТЕНИЯ. `after` — дальше по ленте, `before` —
 *             обратно. Что это значит в терминах времени, зависит от `order`: у ленты
 *             «дальше» это в прошлое, у треда — в будущее.
 *
 * Смешать их — обычная ошибка: у первой же поверхности с обратным порядком «дальше»
 * начинает уводить в другую сторону, и тред открывается с конца. Поэтому сторона скана
 * выводится из пары, а не задаётся отдельно.
 *
 * Почему оба ключа в одну сторону, в отличие от `asc(id)` на остальном сайте: построчное
 * сравнение кортежей осмысленно только при одинаковом направлении. Смешанный порядок
 * пришлось бы писать через `or`, а такая форма уже не ложится на составной индекс одним
 * диапазонным сканом — ради чего keyset и заводился.
 *
 * Под это нужен индекс `(… , key DESC, id DESC)` — с `NULLS FIRST`, иначе он не совпадёт
 * с `ORDER BY` и порядок не отдаст (см. `tests/architecture/index-nulls-order`). Шаг
 * вверх идёт по тому же индексу в обратную сторону — отдельного не нужно.
 *
 * ВАЖНО про шаг назад: он сканирует ПРОТИВ порядка показа, то есть строки приходят задом
 * наперёд. Разворачивать их обязан вызывающий, ПОСЛЕ отсечения лишней строки разведчика:
 * развернуть раньше — значит отрезать не тот конец. Об этом говорит `reverse` в ответе.
 *
 * `where: undefined` при `null`-курсоре — это край ленты: условия нет, и вызывающий кладёт
 * его прямо в `and(...)`, где `undefined` игнорируется. Отдельной ветки «если первая
 * порция» на каждой поверхности из-за этого не заводится.
 *
 * Ключ уходит параметром с явным приведением: он приехал из адреса, и хотя проверен
 * `decodeCursor` до формы `timestamptz`, приведение здесь — не дубль проверки, а
 * ЕДИНСТВЕННОЕ место, где база узнаёт тип. Без него Postgres сравнивал бы `timestamptz`
 * с `text` и падал бы на несуществующем операторе.
 */
export function keysetStep(
  key: Column,
  id: Column,
  cursor: Cursor | null,
  opts: { order?: FeedOrder; dir?: FeedDirection; keyType?: CursorKeyType } = {},
): { where: SQL | undefined; order: SQL[]; reverse: boolean } {
  const { order = 'desc', dir = 'after', keyType = 'time' } = opts
  // Скан идёт в сторону показа, когда шагают вперёд, и против неё — когда назад.
  const scanDesc = dir === 'after' ? order === 'desc' : order !== 'desc'
  // Приведение — по типу ключа поверхности. Тот же тип обязан быть у `decodeCursor`:
  // разойдутся — и курсор одной поверхности, подставленный в адрес другой, уронит её
  // приведением вместо того, чтобы честно отсеяться как непригодный.
  const at = keyType === 'int' ? sql`${cursor?.key}::int` : sql`${cursor?.key}::timestamptz`
  return {
    where: cursor
      ? scanDesc
        ? sql`(${key}, ${id}) < (${at}, ${cursor.id}::uuid)`
        : sql`(${key}, ${id}) > (${at}, ${cursor.id}::uuid)`
      : undefined,
    order: scanDesc ? [sql`${key} desc`, sql`${id} desc`] : [sql`${key} asc`, sql`${id} asc`],
    // Шаг назад всегда сканирует против показа, значит строки приходят задом наперёд.
    reverse: dir === 'before',
  }
}

/**
 * КЛЮЧ КУРСОРА ТЕКСТОМ — колонка, из которой строится курсор следующей порции.
 *
 * Брать типизированное значение колонки НЕЛЬЗЯ: `timestamptz` в Postgres хранит
 * микросекунды, а `Date` в JS — миллисекунды, и drizzle отдаёт колонку уже обрезанной
 * (замер 18.08: в базе `19:02:03.092835`, в приложении `19:02:03.092Z`). Курсор из
 * обрезанного ключа отсекает вместе с показанным и всё, что попало в отброшенные
 * микросекунды, — строки исчезают молча, то есть keyset начинает делать ровно то, ради
 * избавления от чего его и вводят.
 */
export function cursorKey(key: Column): SQL<string> {
  return sql<string>`${key}::text`
}
