import 'server-only'
import { headers } from 'next/headers'

/**
 * IP запроса — или `null`, если запроса нет.
 *
 * ⚠️ ИМЕННО try/catch, А НЕ `headers().catch(...)`. Вне области запроса (фоновая задача,
 * очередь, тест) `headers()` отказывает, и отказ приходит по-разному: то отклонённым
 * промисом, то синхронным броском. `.catch` покрывает только первый вид, и на втором
 * исключение улетает наружу — вызывающий падает целиком.
 *
 * ⚠️ И ПОЧЕМУ ОБЩИЙ ПОМОЩНИК. Этот же разбор написан в девяти местах, и на нём уже
 * дважды обожглись: журнал аудита терял событие, а замер спроса ронял действие в тестах
 * и уронил бы его при вызове из очереди. Один разбор — одна ловушка, закрытая один раз.
 */
export async function requestIp(): Promise<string | null> {
  try {
    const h = await headers()
    return (h.get('x-forwarded-for') ?? '').split(',')[0].trim() || null
  } catch {
    return null
  }
}
