/**
 * ПОВЕСТКА РАЗВИТИЯ — чистая логика: из сигналов в упорядоченный список «что растим и почему».
 *
 * Пробел, который она закрывает: компания умеет производить и улучшать, но не умеет решать,
 * ЧТО производить дальше. Тему выбирал каждый специалист сам за себя, и никто не смотрел на
 * картину целиком — библиотека росла вширь случайно.
 *
 * Устройство — из докладной «Отдел 1: Партнёры + двигатель развития»: сигналы (покрытие ·
 * спрос · качество · бюджет) → повестка = ранжир «айтемов роста» с *почему + сколько +
 * приоритет*. Три вещи здесь принципиальны:
 *
 *   1. НИ ОДНОГО ВЫЗОВА МОДЕЛИ. Всё считается кодом по числам, которые уже есть в БД.
 *      Спрашивать модель «что нам развивать» — это платить за мнение вместо замера.
 *   2. РЕШАЕТ ЧЕЛОВЕК. Петля предлагает, гендиректор одобряет или отклоняет. Одобренное
 *      получает производство как приоритет — вот тут повестка и становится управлением,
 *      а не отчётом.
 *   3. ЧЕСТНОЕ «ПОЧЕМУ». У каждого пункта наверх едут ЧИСЛА, из которых он вырос, а не
 *      формулировка. «Списков по теме 1 при пороге 5» проверяемо; «нужно усилить
 *      направление» — нет.
 */

/** Классы работ. Определяют и вес в ранжире, и кто пункт исполняет. */
export const AGENDA_KINDS = ['deepen', 'canon', 'hire', 'demand', 'quality', 'feed'] as const
export type AgendaKind = (typeof AGENDA_KINDS)[number]

export type AgendaStatus = 'proposed' | 'approved' | 'dismissed' | 'done'

/**
 * Микс направлений из докладной: Стратегия 50 / Покрытие 40 / Спрос 10, плюс резерв ~20% темпа
 * на собственные нужды (починка, каноны, чистка). Здесь он выражен весами классов.
 *
 * Почему резерв не «оставшиеся проценты», а вес: собственные нужды всегда проигрывают
 * росту, если конкурируют с ним на общих основаниях, — и компания зарастает. Вес поднимает
 * их достаточно, чтобы починка попадала в верх повестки, не вытесняя развитие.
 */
export const KIND_WEIGHT: Record<AgendaKind, number> = {
  // Стратегия: углубление домена и найм под непокрытое.
  deepen: 0.5,
  hire: 0.5,
  // Покрытие: канон и фактура под домены, где нам нечем подкрепить утверждения.
  canon: 0.4,
  // Спрос: люди спросили — у нас не нашлось. Пока трафика мало, вес низкий осознанно.
  demand: 0.1,
  // Собственные нужды (резерв): качество и свежесть уже существующего.
  quality: 0.2,
  feed: 0.2,
}

export interface AgendaSignal {
  kind: AgendaKind
  /** Домен/тема, к которой относится работа. '' — общефирменный пункт. */
  domain: string
  /**
   * Сила сигнала [0..1]: насколько остро. Считается на месте сбора из чисел, а не на глаз.
   * За пределы диапазона не пускаем — иначе один шумный сигнал перевесит всю повестку.
   */
  strength: number
  /** Числа, из которых пункт вырос. Едут в интерфейс как есть. */
  why: Record<string, number | string>
}

export interface AgendaItem extends AgendaSignal {
  /** Вес класса × сила сигнала. Больше — выше в повестке. */
  score: number
}

/** Ключ дедупа: один пункт на пару «класс + тема». Иначе повестка растёт каждый проход. */
export const agendaKey = (kind: AgendaKind, domain: string): string => `${kind}:${domain.toLowerCase().trim()}`

const clamp01 = (x: number): number => (Number.isFinite(x) ? Math.min(1, Math.max(0, x)) : 0)

/**
 * Ранжир повестки. Сортировка детерминированная: по счёту, потом по классу, потом по теме —
 * иначе два пункта с равным счётом меняются местами от прогона к прогону, и владелец видит
 * «шевеление» там, где ничего не изменилось.
 */
export function rankAgenda(signals: AgendaSignal[], limit = 12): AgendaItem[] {
  const byKey = new Map<string, AgendaItem>()
  for (const s of signals) {
    const item: AgendaItem = { ...s, strength: clamp01(s.strength), score: KIND_WEIGHT[s.kind] * clamp01(s.strength) }
    const key = agendaKey(s.kind, s.domain)
    // Дубль по ключу — берём более острый: два источника об одном и том же не должны
    // удваивать присутствие темы в повестке.
    const prev = byKey.get(key)
    if (!prev || item.score > prev.score) byKey.set(key, item)
  }
  return [...byKey.values()]
    .filter((i) => i.score > 0)
    .sort((a, b) => b.score - a.score || a.kind.localeCompare(b.kind) || a.domain.localeCompare(b.domain))
    .slice(0, limit)
}

/**
 * Сколько списков по теме считаем достаточным, чтобы тема перестала быть «пробелом».
 * Число грубое и намеренно маленькое: библиотека молодая, и порог 5 уже отличает «тема есть»
 * от «темы нет». Уточнять его нужно на данных, а не в уме.
 */
export const COVERAGE_TARGET = 5

/** Сила сигнала покрытия: 0 при достигнутом пороге, 1 при полном отсутствии темы. */
export const coverageStrength = (lists: number, target = COVERAGE_TARGET): number =>
  clamp01((target - lists) / target)

/**
 * Подпись пункта повестки. Строится КОДОМ из класса и темы — не моделью: подпись обязана
 * означать ровно то, что посчитано, а формулировка от модели незаметно съезжает.
 */
export function agendaLabel(kind: AgendaKind, domain: string, ru: boolean): string {
  const L: Record<AgendaKind, [en: string, ru: string]> = {
    deepen: ['Deepen the topic', 'Углубить тему'],
    canon: ['Collect source material', 'Собрать первоисточники'],
    hire: ['Hire a specialist', 'Нанять специалиста'],
    demand: ['Demand left unanswered', 'Спрос остался без ответа'],
    quality: ['Fix quality', 'Починить качество'],
    feed: ['Revive the feed', 'Оживить ленту'],
  }
  const [en, rus] = L[kind]
  return domain ? `${ru ? rus : en}: ${domain}` : ru ? rus : en
}
