import { isLang, type Lang } from './index'

/**
 * ЯЗЫКОВОЙ ПРЕФИКС В АДРЕСЕ — ТОЛЬКО ЧТОБЫ ЕГО СНЯТЬ.
 *
 * Языка в адресе нет (ADR-0019, подтверждён ADR-0029 от 25.09.2026): адрес страницы один на
 * все языки, язык интерфейса — профиль → кука → `Accept-Language`. С 22 по 25.09 у страниц
 * были адреса `/ru/…` и `/en/…` (setfork-app #950, #959); они уже в индексе и во внешних
 * ссылках, поэтому middleware отвечает на них постоянным перенаправлением на адрес без
 * префикса, а MCP принимает такие ссылки на списки. Для этого и нужен разбор.
 */

/** Кусок пути без языка + язык, если он был указан в адресе. */
export interface SplitPath {
  /** Язык из префикса; `null` — префикса нет. */
  lang: Lang | null
  /** Путь без языкового префикса, всегда начинается со слэша: `/explore`, `/`. */
  rest: string
}

/**
 * Отделяет языковой префикс от остального пути.
 *
 * ⚠️ Префиксом считается ТОЛЬКО полный сегмент: `/ru` и `/ru/...` — да, а `/rust` —
 * нет. Без этой оговорки список с ником `ruslan` или слагом `runbook` уехал бы на
 * другой адрес (та же ловушка, что K40 — шаблон по подстроке).
 */
export function splitLangPath(pathname: string): SplitPath {
  const m = /^\/([a-z]{2})(\/.*)?$/.exec(pathname)
  if (!m) return { lang: null, rest: pathname || '/' }
  const [, code, tail] = m
  if (!isLang(code)) return { lang: null, rest: pathname }
  return { lang: code, rest: tail && tail !== '' ? tail : '/' }
}
