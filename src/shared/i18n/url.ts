import { DEFAULT_LANG, LOCALES, isLang, type Lang } from './index'

/**
 * ЯЗЫК ЖИВЁТ В АДРЕСЕ, А НЕ ТОЛЬКО В ЗАГОЛОВКЕ ЗАПРОСА.
 *
 * До сентября 2026 русский интерфейс отдавался по ТОМУ ЖЕ адресу, что английский, —
 * выбор делал `Accept-Language`. Для человека это работало, для поисковика нет:
 * индексируется один вариант на один адрес, а YandexBot этот заголовок не шлёт вовсе
 * и всегда получал английскую страницу. Русского SetFork в индексе не существовало —
 * ни заголовков, ни описаний, ни текстов списков (аудит 22.09.2026, работа 1).
 *
 * Поэтому у каждого языка теперь свой адрес: `/ru/explore`, `/en/explore`. Разбор
 * `Accept-Language` (`negotiate.ts`) остался прежним и верным — он больше не решает,
 * ЧТО отдать по адресу, а подсказывает, КУДА направить гостя, пришедшего без префикса.
 *
 * Здесь только работа с самим адресом: ни заголовков, ни кук, ни базы. Так её можно
 * прогонять в тестах без окружения — и она общая для middleware, метаданных и карты
 * сайта, чтобы префикс нельзя было собрать тремя способами и разойтись.
 */

/** Кусок пути без языка + язык, если он был явно указан в адресе. */
export interface SplitPath {
  /** Язык из префикса; `null` — префикса не было, язык решается иначе. */
  lang: Lang | null
  /** Путь без языкового префикса, всегда начинается со слэша: `/explore`, `/`. */
  rest: string
}

/**
 * Отделяет языковой префикс от остального пути.
 *
 * ⚠️ Префиксом считается ТОЛЬКО полный сегмент: `/ru` и `/ru/...` — да, а `/rust` —
 * нет. Без этой оговорки список с ником `ruslan` или слагом `runbook` уехал бы в
 * русскую версию, потеряв свой адрес (та же ловушка, что K40 — шаблон по подстроке).
 */
export function splitLangPath(pathname: string): SplitPath {
  const m = /^\/([a-z]{2})(\/.*)?$/.exec(pathname)
  if (!m) return { lang: null, rest: pathname || '/' }
  const [, code, tail] = m
  if (!isLang(code)) return { lang: null, rest: pathname }
  return { lang: code, rest: tail && tail !== '' ? tail : '/' }
}

/**
 * Адрес этого же места на заданном языке.
 *
 * Английский тоже получает префикс: без него `/explore` и `/en/explore` — два адреса
 * с одним содержимым, и поисковику пришлось бы гадать, какой из них главный. Корень
 * без префикса остаётся, но объявляет себя `x-default` и ссылается на языковые
 * варианты — так у гостя, пришедшего по старой ссылке, ничего не ломается.
 */
export function langHref(pathname: string, lang: Lang): string {
  const { rest } = splitLangPath(pathname)
  return rest === '/' ? `/${lang}` : `/${lang}${rest}`
}

/**
 * Взаимные ссылки на языковые версии страницы — для `hreflang`.
 *
 * `x-default` указывает на адрес БЕЗ префикса: это страница, которая сама выбирает
 * язык по заголовку, и именно её поисковику следует показывать тому, чей язык нам
 * неизвестен. Оговорка аудита: Яндекс понимает `hreflang` для подпапок (между
 * доменами — нет), а у нас как раз подпапки.
 */
export function langAlternates(pathname: string, origin = ''): { languages: Record<string, string>; xDefault: string } {
  const { rest } = splitLangPath(pathname)
  const languages: Record<string, string> = {}
  for (const code of LOCALES) languages[code] = `${origin}${langHref(rest, code)}`
  return { languages, xDefault: `${origin}${rest}` }
}

/** Язык по умолчанию — вынесен сюда, чтобы у адресной логики был один источник. */
export const URL_DEFAULT_LANG: Lang = DEFAULT_LANG

/**
 * Заголовок, которым middleware сообщает рендеру язык, взятый ИЗ АДРЕСА.
 *
 * Почему заголовок, хотя кука тоже ставится: кука, выданная ответом, этому же ответу
 * не видна, а язык адреса обязан действовать сразу. Кука — для следующих переходов по
 * внутренним ссылкам без префикса; как и когда её ставят, см. `proceed` в
 * middleware.
 *
 * Имя с префиксом `x-setfork-`, чтобы его нельзя было спутать со стандартным заголовком
 * и чтобы он не пришёл снаружи незамеченным: middleware ставит его сам на каждом
 * запросе с префиксом, а входящий одноимённый заголовок при этом перезаписывается.
 */
export const LANG_HEADER = 'x-setfork-lang'
