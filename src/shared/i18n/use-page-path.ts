'use client'
import { usePathname } from 'next/navigation'
import { splitLangPath } from './url'

/**
 * Путь страницы БЕЗ языкового префикса — для тех, кто по пути РАЗБИРАЕТ, где находится.
 *
 * ⚠️ `usePathname()` отдаёт адрес браузера как есть. Middleware переписывает `/ru/…` на
 * маршрут без префикса только на сервере, и на клиенте после гидратации компонент видит
 * `/ru/alice/list`. Разбор такого пути принимал `ru` за владельца: крошка строила путь
 * к человеку `ru`, вкладка списка не подсвечивалась, действия корня списка пропадали
 * (находка авто-ревью к SEO-1).
 *
 * Кто по пути ПЕРЕХОДИТ (`router.push(pathname + query)`), берёт `usePathname()`
 * напрямую: там префикс нужен, иначе переход молча сбрасывал бы язык адреса.
 */
export function usePagePath(): string {
  return splitLangPath(usePathname() ?? '/').rest
}
