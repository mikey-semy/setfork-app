import 'server-only'
import { isAdminHandle } from '@/shared/auth/admin'

/**
 * Тарифы (единый источник правды). Принцип монетизации (из бенча + разбора MCP-обхода):
 * «сделать список с помощью ИИ» — необходёмый товар (у всех свой ИИ; MCP-создание своим ИИ нам не
 * стоит ничего и его не гейтим). Платят за то, что своей ОДНОЙ моделью не воспроизвести:
 *   • СОВЕТ — мультимодельный синтез (набросок→критика→синтез); он стоит НАМ денег → перк Pro;
 *   • объём/приоритет/веб-поиск; платформа (каноны, форки, слои исполнения).
 *
 * Гейт живёт в СЕРВИСНОМ слое (service.ts / quota.ts), а не в веб-actions — тогда веб, MCP и будущий
 * API наследуют его и обойти нельзя. Сейчас Pro = админ; когда появится оплата (трек Б), planFor
 * будет читать активную подписку из БД — ЕДИНСТВЕННОЕ место правки.
 *
 * Поэтому спрашивать надо ИМЕННО planFor/isPro, а не «админ ли он». Проверка админа
 * даёт сегодня тот же ответ и молча разойдётся завтра: купивший Pro не получил бы
 * перк, который значится в его тарифе. Гейт совета на этом однажды и стоял
 * (реестр проверки 28.07, п.10).
 */
export type Plan = 'free' | 'pro'

/** План пользователя. Пока: админ → pro, остальные → free. Точка подключения подписки. */
export function planFor(handle?: string | null): Plan {
  return isAdminHandle(handle) ? 'pro' : 'free'
}

export function isPro(handle?: string | null): boolean {
  return planFor(handle) === 'pro'
}
