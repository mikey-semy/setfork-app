// Правила имени тега релиза. Живут отдельно от actions.ts, потому что из
// 'use server'-файла можно экспортировать только async-функции, а правила нужны
// и тестам. Зеркальная пара с ядром: services/git_core.rs::is_version_tag —
// меняться обязаны вместе.

/** Форма имени: буквы/цифры и .-_ (до 40 символов), непустое. */
export const TAG_RE = /^[A-Za-z0-9._-]{1,40}$/

/** Имена вида v12 заняты автоматическими тегами версий: по ним ядро считает,
 *  докуда версии уже записаны в git, и отклонит такой релизный тег
 *  (`reserved tag name`). Ровно то, что парсит max_tag_version: `v` + только
 *  цифры; «v1.0», «v2-beta», «V1» остаются человеку. */
export function isReservedTag(tag: string): boolean {
  return /^v\d+$/.test(tag)
}
