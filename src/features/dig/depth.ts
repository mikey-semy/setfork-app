import { DIG_MAX_LEVEL } from '@/shared/ai/dig'

// ⚠️ ОТДЕЛЬНЫМ МОДУЛЕМ, а не рядом с экшенами: файл действий помечен 'use server', и
// каждый его экспорт обязан быть async — синхронная функция роняет СБОРКУ («Server
// Actions must be async functions»). Типы, линт и тесты этого не ловят.

/**
 * Какой слой копаем сейчас: по числу вопросов, на которые УЖЕ ответили.
 *
 * Считаем ОТВЕЧЕННЫЕ ВОПРОСЫ, а не реплики мастеров. Мастер может передать вопрос коллеге,
 * и тогда на один вопрос в ленте ложатся две реплики — передача и ответ коллеги. Счёт по
 * репликам уводил следующий вопрос сразу с первого слоя на третий, мимо слоя про механизм
 * и исключения (поймало авто-ревью #957).
 *
 * Вопрос без ответа (сбой, отказ по бюджету) тоже не в счёт: разговор не должен уходить
 * глубже, чем человек на самом деле спустился. Ниже последнего уровня лестницы не
 * опускаемся — дальше глубина не растёт, растёт болтовня.
 */
export function digDepth(history: Array<{ role: string }>): number {
  let answered = 0
  let awaiting = false // последний вопрос человека ещё ждёт первого ответа
  for (const m of history) {
    if (m.role === 'user') awaiting = true
    else if (awaiting) {
      answered++
      awaiting = false
    }
  }
  return Math.min(answered + 1, DIG_MAX_LEVEL)
}
