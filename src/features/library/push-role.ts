import { withPrDefaults } from './pr-settings'

/** Роль пушащего: ядро исполняет по ней правило пространства имён (Ф5). */
export type PushRole = 'owner' | 'collaborator' | 'contributor'

/** То, что нужно для ответа «открыт ли список» — и ничего сверх. */
export type ContributionGate = {
  visibility: string
  status: string
  moderation: string
  prSettings: unknown
}

/**
 * Ф5: впускать ли посторонних вообще. По умолчанию ВЫКЛЮЧЕНО — и это не
 * осторожность ради осторожности.
 *
 * Порядок выкатки — фронт раньше ядра, иначе владельцы не смогут пушить в main.
 * Но в это окно новый фронт уже выдавал бы роль `contributor`, а СТАРОЕ ядро о
 * поле `actor_role` не знает: protobuf молча игнорирует неизвестные поля, и
 * правила пространства имён там ещё нет. Посторонний в этот промежуток пушил бы
 * прямо в `main` и создавал версию (авто-ревью fe#662).
 *
 * Рубильник разрывает эту связь: код едет выключенным, включается отдельным
 * действием — ПОСЛЕ того, как ядро с Ф5 встало на прод. Проверить просто: в
 * логах старта ядра есть строка про пространство имён, а `git push` постороннего
 * в main отвергается хуком, а не роутом.
 *
 * Порядок именно такой, а не «включить и посмотреть»: цена ошибки —
 * посторонний с правом записи в main, то есть новая версия чужого списка.
 */
export const contributorsEnabled = (): boolean => process.env.SETFORK_GIT_CONTRIBUTORS === '1'

/**
 * Ф5: открыт ли список для правок ПОСТОРОННИХ — тот же вопрос, на который
 * отвечает веб-форма предложений.
 *
 * Отдельным модулем, а не строчкой в роуте, по той же причине, по которой
 * отдельно живёт политика повторов зеркала: правило нужно и роуту, и тесту, а
 * тест, повторяющий правило своей копией, проверяет копию. Разъехавшись, они
 * дали бы худший из возможных исходов — «предлагайте» в браузере и «нельзя» в
 * терминале на один и тот же список.
 *
 * Условия намеренно совпадают с веб-путём: список публичный, опубликованный,
 * прошедший модерацию, и владелец не сузил круг предлагающих.
 */
export function openForContributions(meta: ContributionGate): boolean {
  return (
    meta.visibility === 'public' &&
    meta.status === 'published' &&
    meta.moderation === 'active' &&
    withPrDefaults(meta.prSettings).allowFrom === 'all'
  )
}
