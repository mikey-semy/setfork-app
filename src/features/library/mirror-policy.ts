import { envNumber } from '@/shared/env'

/**
 * Ф2: политика повторов упавшего пуша зеркала — ОДНО место для правила.
 *
 * Отдельным модулем от `mirror-jobs`, потому что правило нужно двоим: тому, кто
 * повторяет, и настройкам, которые называют владельцу время следующей попытки.
 * Разъехавшись, они начали бы врать. Здесь нет ни базы, ни `server-only` —
 * значит, страница настроек не тянет за собой очередь задач ради одного числа.
 *
 * ⚠️ ПОВТОРЫ НЕ ПРЕКРАЩАЮТСЯ НИКОГДА — только разрежаются до раза в сутки.
 * Первая версия останавливала их после N неудач («почините и нажмите
 * Синхронизировать»), и это было хуже по двум причинам:
 *
 *   * половина причин чинится НА СТОРОНЕ ФОРДЖИ и без нашего участия — токен
 *     перевыпустили, репозиторий вернули, у форджи кончилась авария. Остановка
 *     превращает самолечащийся сбой в требующий ручного действия, о котором
 *     владелец узнает, только заглянув в настройки;
 *   * цена «пробовать вечно» на потолке — один запрос в сутки на зеркало.
 *
 * Так же устроено у Gitea (MIT, ADR-0013 разрешает смотреть): периодический
 * проход `Update()` берёт ограниченную пачку зеркал (`PushMirrorsIterate` с
 * лимитом), очередь отбрасывает дубли — и НИ отключения после серии неудач, НИ
 * счётчика попыток там нет вовсе; ошибка просто лежит в `LastError`.
 *
 * Мы всё же считаем неудачи, но ради двух других вещей: паузы (чтобы не долбить
 * упавшую форджу каждые пять минут) и честного текста в настройках — после
 * `MIRROR_HELP_AFTER_ATTEMPTS` подряд сбой уже точно не транзиентный, и об этом
 * стоит сказать прямо, продолжая пробовать.
 */

/**
 * После скольких неудач подряд перестаём называть это временным сбоем и говорим
 * владельцу, что, похоже, нужен его токен. Повторы при этом продолжаются.
 *
 * Восемь — потому что столько ступеней лестницы пауз (10, 20, 40, 80 мин, 2.7,
 * 5.3, 10.6 ч, дальше сутки) укладываются примерно в двое суток. Дневная авария
 * форджи не должна доводить до этого текста, а двое суток — уже не авария.
 */
export const MIRROR_HELP_AFTER_ATTEMPTS = envNumber('SETFORK_MIRROR_HELP_AFTER', 8)

/** База паузы между повторами. */
const BACKOFF_MS = envNumber('SETFORK_MIRROR_BACKOFF_MIN', 10) * 60_000

/** Потолок паузы: дальше редить смысла нет, зеркало обязано догнать истину. */
const MAX_BACKOFF_MS = 24 * 3600_000

/**
 * Пауза после `attempts` неудач подряд — экспонента с потолком в сутки.
 * Отозванный токен чинят руками и не за минуту, поэтому пятая попытка уместна
 * через часы, а не пять раз подряд через десять минут.
 */
export function mirrorRetryDelayMs(attempts: number): number {
  return Math.min(BACKOFF_MS * 2 ** Math.max(0, attempts - 1), MAX_BACKOFF_MS)
}

/**
 * Когда зеркало можно трогать снова. `syncedAt` — время последней ПОПЫТКИ:
 * ядро обновляет отметку при любом исходе, включая неудачный. null (не пробовали
 * ни разу) — можно сразу.
 */
export function mirrorRetryDueAt(attempts: number, syncedAt: Date | null): Date {
  return syncedAt ? new Date(syncedAt.getTime() + mirrorRetryDelayMs(attempts)) : new Date(0)
}
