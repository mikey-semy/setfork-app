/**
 * Парсинг @-упоминаний из markdown-текста (issue, комментарии, правки).
 * Чистая функция без server-only/БД — удобно тестировать в изоляции.
 *
 * Handle совпадает с валидацией регистрации: [a-z0-9-]{3,30}.
 * Символ перед «@» не должен быть буквенно-цифровым/`_`/`/`/`@`/`-`, чтобы
 * не ловить e-mail (foo@bar), пути (a/@b) и повторные «@@».
 */
const MENTION_RE = /(^|[^a-zA-Z0-9_/@-])@([a-z0-9-]{3,30})\b/gi

/**
 * ⚠️ АДРЕСА ВЫРЕЗАЕМ ДО РАЗБОРА: «@» внутри ссылки принадлежит ссылке, а не человеку.
 *
 * Запрет `/@` спасал только от пути (`site/@user`), а `https://site/p?user=@alice`
 * разбор проходил — перед «@» стоит «=». Уведомление при этом уходило живому тёзке, и
 * текст ссылки выбирал не тот, от чьего имени оно приходило: садовник кладёт в задачу
 * битые адреса ИЗ ЧУЖОГО списка, а человек цитирует чужую страницу.
 *
 * Вырезание — правило про МЕСТО, а не про соседний символ: перечислять «=», «?», «&»
 * пришлось бы бесконечно, и каждый новый вид адреса открывал бы дырку заново.
 */
/**
 * ⚠️ АДРЕС КОНЧАЕТСЯ НЕ ТОЛЬКО ПРОБЕЛОМ. `\S+` съедал закрывающую скобку markdown-ссылки
 * и всё, что шло за ней вплотную: в `[сайт](https://site/a)@dev-two` упоминание стояло
 * СНАРУЖИ адреса, а исчезало вместе с ним. То же с угловыми скобками (`<url>@dev`).
 *
 * Поэтому граница — пробел ИЛИ markdown-ограничитель. Цена: адрес, у которого скобка
 * внутри (`…/x_(y)`), обрежется на ней, и хвост попадёт в разбор упоминаний. Это
 * безобиднее обратного: пропущенное обращение к человеку — потеря, а хвост адреса почти
 * никогда не выглядит как «@имя».
 */
const URL_RE = /\b(?:https?:\/\/|www\.)[^\s<>()[\]"']+/gi

/** Уникальные handle-и (в нижнем регистре) из текста; пустой массив, если нет. */
export function extractHandles(text: string | null | undefined): string[] {
  if (!text) return []
  const out = new Set<string>()
  // Замена ПРОБЕЛОМ, а не пустой строкой: иначе «см. https://x.com @alice» склеилось бы
  // в «см. @alice» — здесь безобидно, но соседние слова слипались бы и в других разборах.
  for (const m of text.replace(URL_RE, ' ').matchAll(MENTION_RE)) out.add(m[2].toLowerCase())
  return [...out]
}
