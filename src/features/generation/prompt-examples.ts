import { t, type Lang, type TKey } from '@/shared/i18n'

/**
 * ПРИМЕРЫ ЗАПРОСОВ ДЛЯ ГЕНЕРАЦИИ — ЗАДАЧИ, А НЕ ЧУЖИЕ ЗАГОЛОВКИ.
 *
 * Раньше сюда подставлялись названия УЖЕ СУЩЕСТВУЮЩИХ публичных списков
 * (`sampleListTitles`), и человек видел предложение «создать» то, что у него уже есть
 * — вплоть до собственных списков (замечание владельца 02.09.2026: «предложка глупо
 * предлагает то, что уже есть — смысл?»).
 *
 * Задумка была «как подсказки поисковика», но аналогия неверна: поисковик подсказывает
 * ЗАПРОС, который человек может задать, а не существующую страницу с предложением
 * создать её заново. Продукты, где просят описать задачу текстом, показывают
 * придуманные примеры, а не чужие работы: ChatGPT — четыре карточки-примера,
 * Perplexity — примеры вопросов, v0 — примеры промптов.
 *
 * Примеры живут в словаре, а не здесь строками: третий язык не должен требовать правки
 * этого файла. Витрину «что уже есть» показывает главная — там живые заголовки на
 * месте, потому что ведут на сами списки.
 */
const KEYS: TKey[] = [
  'generation.example1',
  'generation.example2',
  'generation.example3',
  'generation.example4',
  'generation.example5',
  'generation.example6',
]

export function promptExamples(lang: Lang, max = KEYS.length): string[] {
  return KEYS.slice(0, max).map((k) => t(k, lang))
}
