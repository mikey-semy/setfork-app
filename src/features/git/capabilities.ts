import { gitCore } from './core'

/**
 * Ф5: подтверждает ли ядро ПРЯМО СЕЙЧАС, что исполняет роли.
 *
 * Пока не подтвердило — постороннего не пускаем: он оказался бы у ядра, которое
 * роль не смотрит вовсе, и `git push` в main прошёл бы как обычная запись.
 * Владельца и соавтора это не касается — их право от версии ядра не зависит.
 *
 * # Почему ответ НЕ кэшируется
 *
 * Кэш здесь был, и его пришлось убрать: он отменял ровно тот сценарий, ради
 * которого проверка и заведена. Ядро откатили назад — а фронт ещё десять минут
 * помнит «умеет» и продолжает пускать посторонних к ядру без правила
 * (авто-ревью fe#662). Право доступа, запомненное про запас, — это право,
 * действующее дольше основания.
 *
 * Цена отказа от кэша мала и заведомо известна: лишний unary-вызов к соседнему
 * контейнеру, и только на пути ПОСТОРОННЕГО — у владельца и соавтора до этой
 * проверки дело не доходит. На фоне приёма пака это не измеримо.
 *
 * Дедлайн явный: без него зависшее ядро держало бы пуш до бесконечности вместо
 * честного отказа. Секунды хватает с запасом — вызов не делает ничего, кроме
 * ответа константой.
 */
const CAP_TIMEOUT_MS = 1000

export async function coreEnforcesPushRoles(): Promise<boolean> {
  const { enforcesPushRoles } = await gitCore.capabilities({ timeoutMs: CAP_TIMEOUT_MS })
  return enforcesPushRoles
}
