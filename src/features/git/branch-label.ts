import { t, type Lang } from '@/shared/i18n'

/**
 * Как называть ветку в интерфейсе.
 *
 * # Зачем отдельная функция
 *
 * Ветку под правку из терминала называет СЕРВЕР: пуш в `refs/for/main` кладёт
 * коммиты в `u/<идентификатор>/<база>` (Ф4). Идентификатор внутренний — человек
 * его не набирал, ни во что не скопирует и ни с чем не соотнесёт; в интерфейсе
 * это просто шум из шестнадцатеричных цифр.
 *
 * Замена подписи стояла в одном месте — в списке предложений, — а те же ветки
 * показывались ещё на странице предложения и в селекторе веток на публичной
 * странице списка, где их видит вообще любой читатель (авто-ревью fe#662).
 * Поэтому решение живёт функцией, а не условием по месту: следующая поверхность
 * с ветками получит правило даром.
 *
 * # Почему по форме имени, а не по признаку в базе
 *
 * Имя ветки — единственное, что есть у всех трёх поверхностей: селектор веток
 * читает git, а не предложения, и признака «эту завёл сервер» ему взять негде.
 * Форма же задана нами и проверяется хуком: `u/<идентификатор>/<база>`, где
 * идентификатор — UUID пользователя.
 *
 * Шаблон намеренно узкий, до формы UUID. Широкое `u/<что угодно>/<что угодно>`
 * отбирало бы имя у настоящей ветки: владелец вправе запушить из терминала
 * `u/team/main`, и она получила бы чужую подпись и пропала из селектора
 * (авто-ревью fe#662). Через интерфейс такую ветку не создать — там разрешены
 * только буквы, цифры и `.-_`, — но `git push` слэши не запрещает.
 */
const SERVER_BRANCH = /^u\/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\/[^/]+$/i

/** Ветку назвал сервер (правка из терминала), а не человек. */
export const isServerBranch = (ref: string) => SERVER_BRANCH.test(ref)

/** Подпись ветки для человека: своё имя — как есть, серверное — словами. */
export const branchLabel = (ref: string, lang: Lang) =>
  isServerBranch(ref) ? t('prFromTerminal', lang) : ref
