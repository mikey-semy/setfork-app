import 'server-only'
import { eq } from 'drizzle-orm'
import { db, users } from '@/shared/db'
import { negotiateLang } from '@/shared/i18n/negotiate'
import type { Lang } from '@/shared/i18n'

/**
 * Кто пушит — глазами доставки: ник для переходного имени ветки и язык, на котором
 * человек прочитает отказы прямо в выводе `git push`.
 *
 * Отдельно от маршрута, потому что это не форма провода, а обращение к профилю: у
 * транспорта нет причин знать ни таблицу пользователей, ни правила выбора языка.
 */
export interface GitActorContext {
  lang: Lang
  handle: string
}

/**
 * Язык отказов, которые печатает `pre-receive` ВНУТРИ ядра (И2).
 *
 * Переводить их некому — между ядром и git-клиентом никого нет. Поэтому язык
 * определяем здесь и передаём ядру, а оно лишь выставляет его процессу receive-pack
 * переменной окружения.
 *
 * Порядок: осознанный выбор в профиле → локаль git-клиента → английский.
 *
 * ⚠️ «Осознанный выбор» приходится ПРИБЛИЖАТЬ. `users.lang` объявлен NOT NULL DEFAULT
 * 'en', то есть у каждого пользователя он непустой, и отличить «выбрал английский» от
 * «никогда не открывал настройки» на уровне данных нельзя. Если читать профиль как есть,
 * заголовок не сработает НИКОГДА: русскоязычный пользователь, не менявший настройки,
 * получал бы английские отказы при русском терминале (находка авто-ревью fe#632).
 *
 * Поэтому значение по умолчанию трактуем как «выбора не было» и спрашиваем клиента.
 * Цена приближения одна: тот, кто ОСОЗНАННО выбрал английский, но пушит из русской
 * локали, получит русский текст — то есть язык своего же терминала. Это мягче, чем
 * игнорировать локаль у всех остальных.
 *
 * Чинится по-настоящему отдельным признаком «язык выбран явно» (nullable-колонка или
 * флаг) — записано в трек core-i18n как открытый вопрос.
 *
 * Английский по умолчанию — решение владельца: git-инструментарий англоязычен, и
 * незнакомый язык в выводе `git push` читается как поломка, а не как забота.
 */
export async function gitActorContext(userId: string, acceptLanguage: string | null): Promise<GitActorContext> {
  const [u] = await db.select({ lang: users.lang, handle: users.handle }).from(users).where(eq(users.id, userId)).limit(1)
  return { lang: pickLang(u?.lang, acceptLanguage), handle: u?.handle ?? '' }
}

/** Профиль важнее заголовка; разбор самого заголовка — общий для всего приложения. */
function pickLang(profile: string | undefined, acceptLanguage: string | null): Lang {
  // Не 'en' — значит язык меняли руками: это и есть осознанный выбор.
  if (profile && profile !== 'en') return profile as Lang
  return negotiateLang(acceptLanguage)
}
