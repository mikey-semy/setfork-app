// Ритм ухода — ОДНО место на весь садовник.
//
// Эти два числа связывают три разных решения, и потому обязаны быть одним
// значением, а не тремя одинаковыми: `account` ими будит проход, `candidates`
// тем же окном решает, кого в этом проходе НЕ трогать («недавно предлагали»).
// Разъехавшись, они дают самый неприятный сорт поломки: проход исправно
// просыпается и исправно ничего не делает, потому что окно отбора шире ритма.
//
// До 11.08 копий было три: `service.ts`, `sweep/account.ts`, `sweep/candidates.ts`
// (в `service.ts` — уже мёртвые). Осадок частичного разбора #715.

/** Ритм обычного прохода — он же задаёт окно «недавно предлагали». */
export const GARDENER_EVERY_DAYS = 2

/**
 * Ритм для живых списков. Шесть часов, а не час: материал в поток приходит по своему
 * расписанию, и чаще будить проход значит платить за refine там, где новостей ещё нет.
 * Проверка «нечего добавить» стоит один запрос и вызова модели не делает.
 */
export const LIVING_EVERY_HOURS = 6

/** Сколько списков берём за один проход. */
export const BATCH = Number(process.env.GARDENER_BATCH ?? 3)
