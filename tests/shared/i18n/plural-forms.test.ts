import { describe, expect, it } from 'vitest'
import { plural } from '@/shared/i18n'

/**
 * Формы новых счётных слов — на числах, где русский язык расходится сам с собой:
 * 1, 2, 5, 11 (одиннадцать берёт форму множества, хотя кончается на единицу) и 21.
 */
describe('склонение при числе', () => {
  const ru = (n: number, key: Parameters<typeof plural>[1]) => plural(n, key, 'ru')

  it('комментарии — то самое место, где стояло «0 комментировать»', () => {
    expect([0, 1, 2, 5, 11, 21].map((n) => `${n} ${ru(n, 'comments')}`)).toEqual([
      '0 комментариев',
      '1 комментарий',
      '2 комментария',
      '5 комментариев',
      '11 комментариев',
      '21 комментарий',
    ])
  })

  it('прилагательные при числе склоняются так же, как существительные', () => {
    expect([1, 2, 5].map((n) => `${n} ${ru(n, 'openIssues')}`)).toEqual(['1 открытая', '2 открытые', '5 открытых'])
    expect([1, 2, 5].map((n) => `${n} ${ru(n, 'closedIssues')}`)).toEqual(['1 закрытая', '2 закрытые', '5 закрытых'])
  })

  it('подписчики и строки', () => {
    expect([1, 3, 7].map((n) => ru(n, 'followers'))).toEqual(['подписчик', 'подписчика', 'подписчиков'])
    expect([1, 3, 7].map((n) => ru(n, 'rows'))).toEqual(['строка', 'строки', 'строк'])
  })

  it('по-английски форма одна на всё, кроме единицы — поэтому дефект и переживал английский экран', () => {
    expect([0, 1, 2, 11].map((n) => `${n} ${plural(n, 'comments', 'en')}`)).toEqual([
      '0 comments',
      '1 comment',
      '2 comments',
      '11 comments',
    ])
  })
})
