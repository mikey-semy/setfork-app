import { describe, expect, it } from 'vitest'
import { editKey, tr } from '@/shared/i18n'

/**
 * Под какой ключ пишется правка текста списка (ADR-0030): ключ ПОКАЗАННОГО текста; показывать
 * нечего — язык оригинала, иначе интерфейс. Сверяем с тем, что показывает `tr`: правка обязана
 * лечь туда, откуда текст взят, — иначе перевод затрёт оригинал или ключи раздвоятся.
 */
describe('editKey', () => {
  it.each([
    // Белорусский список без перевода, русский интерфейс — показан и правится оригинал.
    ['ru', 'be', { be: 'Суп' }, 'be'],
    // Есть русский перевод — правят перевод.
    ['ru', 'be', { be: 'Суп', ru: 'Суп' }, 'ru'],
    // ⚠️ Белорусский с английским переводом, русский интерфейс: показан английский — правка в `en`,
    // а не поверх белорусского оригинала.
    ['ru', 'be', { be: 'Нарэзаць', en: 'Cut' }, 'en'],
    // Язык не записан — ключ показанного.
    ['en', null, { ru: 'Суп' }, 'ru'],
    // Текста нет — язык оригинала, иначе интерфейс.
    ['ru', 'be', {}, 'be'],
    ['ru', null, {}, 'ru'],
    ['ru', 'russian', {}, 'ru'],
  ] as const)('интерфейс %s, язык %s, текст %j → %s', (ui, stored, text, want) => {
    const key = editKey(ui, stored, text)
    expect(key).toBe(want)
    // Правка ложится туда, откуда показан текст.
    if (Object.keys(text).length) expect((text as Record<string, string>)[key]).toBe(tr(text, ui))
  })
})
