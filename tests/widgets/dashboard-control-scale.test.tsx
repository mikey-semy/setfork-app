import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { CONTROL_H } from '@/shared/ui/control'

/**
 * ⚠️ КОНТРОЛЫ ОДНОГО ЭКРАНА — ОДНОЙ СТУПЕНИ.
 *
 * На дашборде их было три: поиск виджета 24px (`size="xs"`), «Фильтр» и кнопки шапки
 * 32px, кнопки пагинации 44px. Владелец увидел это на телефоне и спросил, есть ли у нас
 * вообще единый центр констант. Центр есть — `CONTROL_H`; разъезжалось потому, что
 * каждое место выбирало ступень само, а 44px у пагинации были даже не выбором вида:
 * `TOUCH_MIN_BOX` растил кнопку на грубом указателе.
 *
 * Правило стережёт оба источника: ступень берётся из шкалы (а не пишется числом) и
 * тач-цель добирается ЗОНОЙ, а не ростом видимой кнопки.
 */
/** Комментарии гасим: они законно НАЗЫВАЮТ то, что запрещено в коде. */
const read = (p: string) =>
  readFileSync(new URL('../../' + p, import.meta.url).pathname, 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '))
    .replace(/^\s*\/\/.*$/gm, (m) => m.replace(/[^\n]/g, ' '))

describe('шкала контролов дашборда', () => {
  it('компактная листалка добирает палец зоной, а не ростом', () => {
    // Обычная листалка растёт сама и правильно делает: там номера страниц стоят
    // вплотную, и зоны соседей налезали бы друг на друга. Компактная — две стрелки
    // без соседей по горизонтали, ей рост не нужен.
    const src = read('src/shared/ui/Pagination.tsx')
    expect(src, 'ступень вида — из шкалы').toMatch(/CONTROL_H\.md/)
    expect(src, 'вид у двух листалок один, разная только тач-цель').toMatch(
      /const touch = compact \? TOUCH_HIT : TOUCH_MIN_BOX/,
    )
  })

  it('поиск виджета — той же ступени, что соседи по блоку', () => {
    const src = read('src/widgets/ListsPanel.tsx')
    const m = /<SearchField[^>]*size="(\w+)"/.exec(src)
    expect(m, 'поиск панели не найден — правило потеряло предмет').not.toBeNull()
    expect(m?.[1], 'ступень поиска разошлась с «Фильтром» и пагинацией').toBe('md')
  })

  it('ступень md — та самая, что у кнопок: число берётся из шкалы, а не из теста', () => {
    // Если шкалу переставят, тест не должен молча остаться зелёным на старом числе.
    expect(CONTROL_H.md).toBe('h-8')
  })
})
