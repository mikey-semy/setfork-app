import { describe, expect, it } from 'vitest'
import { readdirSync, readFileSync, statSync } from 'node:fs'
import { join } from 'node:path'

/**
 * КТО СОБИРАЕТ ШАГ РУКАМИ — ОБЯЗАН НЕСТИ ЗАЩИТНЫЕ ПОМЕТКИ.
 *
 * Рукописных конвертеров было четыре, и каждый вёл свой список полей: «использовать как
 * шаблон», форк, приём сгенерированного кандидата, перевод. Списки расходились молча —
 * форк терял «разрушительный пункт», и закомментированный `# make reset` собирался в
 * собранном скрипте ИСПОЛНЯЕМЫМ. Чинили дважды, и оба раза дочиняли по одному полю.
 *
 * ⚠️ УЗДА ЛОВИТ ПОТЕРЮ ПОЛЯ, А НЕ ВТОРОЙ МАППЕР. Запрещать рукописную сборку целиком
 * нельзя: на границе домена и базы живут переводчики между ДВУМЯ моделями, и звать
 * общий конвертер им нечем — у него другая цель. Первая версия этой узды их и поймала,
 * хотя они не копии пути записи. Значит проверять надо свойство: собрал шаг руками —
 * перенеси пометки. Их отсутствие и есть тот самый дефект.
 *
 * Пометки выбраны не произвольно: обе несут ЗАЩИТУ, и обе теряются незаметно —
 * «здесь нужен человек» снимает чужой опыт с плеч читателя, «разрушительный пункт»
 * удерживает опасную команду от попадания в исполняемый скрипт.
 */
const CANONICAL = 'src/shared/lib/step-input.ts'
const GUARDED = ['needsHuman', 'danger']

const walk = (dir: string): string[] =>
  readdirSync(dir).flatMap((n) => {
    const p = join(dir, n)
    return statSync(p).isDirectory() ? walk(p) : /\.tsx?$/.test(p) ? [p] : []
  })

/**
 * Признак рукописной сборки шага НА ЗАПИСЬ: нумерация рядом с картинкой в форме
 * хранилища. Смотрим КАЖДУЮ сборку отдельно, а не файл целиком: в одном файле рядом
 * живут исправленный путь и забытый, и проверка «в файле упоминается toStepInput»
 * пропускала второй. Ровно это и показала мутация — форк вернули к рукописному
 * маппингу без `danger`, а узда осталась зелёной, потому что в соседней функции
 * общий конвертер звался.
 */
const assemblies = (src: string): string[] => {
  const out: string[] = []
  const re = /n:\s*i\s*\+\s*1/g
  let m: RegExpExecArray | null
  while ((m = re.exec(src))) out.push(src.slice(m.index, m.index + 900))
  return out.filter((a) => /imageRef:/.test(a))
}

describe('рукописная сборка шага', () => {
  it('⚠️ несёт «здесь нужен человек» и «разрушительный пункт» — или зовёт общий конвертер', () => {
    const offenders: string[] = []
    for (const path of walk('src').map((p) => p.replace(/\\/g, '/'))) {
      if (path === CANONICAL) continue
      for (const body of assemblies(readFileSync(path, 'utf8'))) {
        const missing = GUARDED.filter((f) => !body.includes(`${f}:`))
        if (missing.length) offenders.push(`${path}: не переносит ${missing.join(', ')}`)
      }
    }
    expect(
      offenders,
      'тут собирают шаг руками и теряют защитную пометку: перенесите её явно или зовите toStepInput',
    ).toEqual([])
  })
})
