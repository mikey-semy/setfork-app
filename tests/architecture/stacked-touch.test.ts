import { describe, expect, it } from 'vitest'
import { stackedHits } from '../../scripts/lib/stacked-hit.mjs'
import { mixedTouchRows } from '../../scripts/lib/row-touch.mjs'

/**
 * ЗОНЫ НАЖАТИЯ НЕ ВИСЯТ ДРУГ НА ДРУГЕ.
 *
 * `touch="hit"` — дефолт у Button и IconButton, и для ряда по горизонтали он правильный:
 * область нажатия растёт до 44px вверх и вниз, в пустоту, места в потоке не занимая. Для
 * кнопок, стоящих В СТОЛБИК, тот же дефолт — ловушка: две кнопки по 24px получают зоны по
 * 44px, зоны перекрываются примерно на 20px, и тап у границы делает действие СОСЕДА.
 *
 * Это хуже мелкой цели. Промах человек видит и повторяет; тихое срабатывание не того он
 * не видит вовсе — в квизе стрелки порядка двигали пункт в обратную сторону (найдено
 * авто-ревью 27.08.2026, прецедент того же решения уже был в редакторе, QuizSort).
 *
 * Лечится `touch="grow"` (кнопка растёт сама, место резервируется) или `TOUCH_HIT_ROW`
 * (зона с резервом). Проверка ищет статически и проверена мутацией: снимаешь `touch` —
 * краснеет.
 */
describe('тач-цели', () => {
  it('кнопки в столбик не перекрываются зонами нажатия', () => {
    const hits = stackedHits()
    expect(
      hits.map((h) => `${h.path}:${h.line} — ${h.count} кнопки подряд без touch`),
      `Кнопки стоят в столбик с дефолтным touch="hit": их зоны нажатия по 44px наложатся,\n` +
        `и палец у границы сделает действие соседней кнопки.\n` +
        `Поставь touch="grow" (кнопка растёт, место резервируется) — так сделано в QuizSort.`,
    ).toEqual([])
  })
})

describe('политика тач-цели в ряду', () => {
  it('в одном ряду все контролы добирают палец ОДИНАКОВО', () => {
    // Способа два, и оба законные: контрол РАСТЁТ на грубом указателе (`grow`) либо
    // держит ступень и добирает цель невидимой зоной (`hit`/`fixed`). Смешать их в одном
    // ряду значит развалить его на сенсоре: один станет 44px, сосед останется 32px.
    //
    // ⚠️ Дефект видят не все. На мыши ряд ровный, поэтому разработчик своего дефекта не
    // видит вовсе — 27.08.2026 владелец назвал «кнопка не по высоте поиска» в ТРЁХ разных
    // местах, а `ui-sizes` докладывал «рядов с разными ступенями: 0»: ступень у всех была
    // одна, расходилась ПОЛИТИКА, и её не сравнивал никто. Зелёный гейт при разъехавшемся
    // интерфейсе — худшее, что счётчик может сделать.
    const rows = mixedTouchRows()
    expect(
      rows.map((r) => `${r.path}:${r.line} — ${r.tags.join(' + ')}`),
      'В одном ряду контролы добирают тач-цель по-разному: на сенсоре ряд разъедется.\n' +
        'Выбери одну политику на ряд: grow — где высоту ряда задают сами контролы;\n' +
        'fixed/hit — где её задаёт полоса (шапка, тулбар) и рост её раздувает.',
    ).toEqual([])
  })
})
