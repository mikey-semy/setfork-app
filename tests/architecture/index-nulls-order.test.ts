import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'

/**
 * ПОРЯДОК ИНДЕКСА ОБЯЗАН СОВПАДАТЬ С `ORDER BY` — ВКЛЮЧАЯ МЕСТО NULL.
 *
 * `ORDER BY x DESC` в SQL значит `DESC NULLS FIRST`. А `.desc()` у drizzle строит
 * индекс `DESC NULLS LAST`. Порядки РАЗНЫЕ, и планировщик такой индекс для сортировки
 * взять не может — даже когда колонка NOT NULL и разницы в данных физически нет.
 *
 * Отказ молчаливый, и это главное: индекс существует, `\d` его показывает, ревью
 * видит строку в схеме — а запрос всё равно идёт сортировкой по всему корпусу. Замер
 * на 20 000 списках: у частичного индекса публичной ленты (`templates_pub_updated_idx`),
 * заведённого ровно под этот запрос, планировщик выбирал `Seq Scan` + `top-N heapsort`
 * по всем 20 002 строкам; с `NULLS FIRST` — `Index Scan` на 20 строк. Индекс лежал
 * мёртвым с момента появления.
 *
 * Поэтому правило проверяет машина: у сортирующей колонки индекса, объявленной
 * `.desc()`, обязан стоять `.nullsFirst()`. Ловим КЛАСС: семь колонок в схеме страдали
 * одним и тем же, и починка каждой по отдельности оставляет правило в голове того,
 * кто чинил.
 *
 * Обратный случай (`ORDER BY x DESC NULLS LAST` в запросе под индекс `.desc()` без
 * `.nullsFirst()`) тест не разбирает: в схеме таких запросов нет, а делать вид, что
 * проверка это учитывает, не надо. Появятся — правило придётся уточнять здесь же.
 */

const SCHEMA = 'src/shared/db/schema.ts'

/**
 * Строки КОДА со `.desc()`. Комментарии отбрасываются: этот же файл объясняет правило
 * словами, и без отбрасывания проверка ловила бы собственное объяснение.
 *
 * Вызовы `desc()` из drizzle-orm (в запросах) сюда не попадают и без фильтра: у них
 * другая форма — `desc(x)`, а не `x.desc()`.
 */
const descLines = (): Array<{ line: string; n: number }> =>
  readFileSync(SCHEMA, 'utf8')
    .split('\n')
    .map((line, i) => ({ line: line.trim(), n: i + 1 }))
    .filter(({ line }) => !line.startsWith('//') && !line.startsWith('*') && !line.startsWith('/*'))
    .filter(({ line }) => /\.desc\(\)/.test(line))

describe('порядок NULL в индексах совпадает с ORDER BY', () => {
  it('у каждой .desc()-колонки индекса стоит .nullsFirst()', () => {
    const bad = descLines()
      .filter(({ line }) => !/\.desc\(\)\.nullsFirst\(\)/.test(line))
      .map(({ line, n }) => `${SCHEMA}:${n} ${line}`)

    expect(bad).toEqual([])
  })

  it('проверка не выродилась: .desc()-колонки в схеме вообще есть', () => {
    // Если .desc() из схемы однажды исчезнет совсем, первый тест станет зелёным
    // ни о чём — и правило тихо перестанет проверяться.
    expect(descLines().length).toBeGreaterThanOrEqual(7)
  })
})
