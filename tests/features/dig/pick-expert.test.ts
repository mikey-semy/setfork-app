import { describe, expect, it } from 'vitest'
import { pickExpert } from '@/features/dig/pick-expert'

/**
 * В ШАХТУ СПУСКАЕТСЯ МАСТЕР ПО РЕМЕСЛУ — И ЛИНЗА У ВСЕХ ОДНА.
 *
 * Выбор гнома для раскопки жил со своей копией доменной линзы, и работала она ПО
 * ПОДСТРОКЕ: `'not-programming'.includes('programming')` истинно, поэтому список
 * «не про программирование» доставался Кодеру. Канон `tagMatches` специально сделан не
 * подстрокой — этот же дефект уже ловили на раздаче ухода садовником и на фильтре
 * прецедентов совета, и рядом с каноном записано: «три копии одного правила
 * разъезжаются». Копия здесь была четвёртой.
 *
 * ⚠️ Тест на КЛАСС: не «этот тег этому гному», а «выбор подчиняется тому же правилу,
 * что и прецеденты». Появится новая форма тега — она попадёт под проверку сама.
 */

const roster = [
  { id: 'devops', domains: ['deploy', 'devops', 'ci'] },
  { id: 'coder', domains: ['programming', 'api'] },
  { id: 'chef', domains: ['готовка', 'cooking'] },
  { id: 'generalist', domains: ['*'] },
]

const idFor = (tags: string[], chosen?: string) => pickExpert(roster, tags, chosen)?.id

describe('выбор гнома для раскопки', () => {
  it.each([
    ['отрицание темы не отдаёт список мастеру этой темы', ['not-programming'], 'generalist'],
    ['по-русски тоже', ['не-готовка'], 'generalist'],
    ['приставка anti- не обманывает', ['anti-devops'], 'generalist'],
  ])('%s', (_name, tags, expected) => {
    expect(idFor(tags), 'линза снова сопоставляет по подстроке').toBe(expected)
  })

  // ⚠️ Обратная сторона: правило, которое никого не находит, бесполезно так же, как
  // дырявое — человек получит универсала там, где мастер есть.
  it.each([
    ['точное совпадение', ['devops'], 'devops'],
    ['форма слова: deployments → deploy', ['deployments'], 'devops'],
    ['слово внутри составного тега', ['ci-cd'], 'devops'],
    ['русский домен мастера', ['готовка'], 'chef'],
  ])('честное совпадение находит мастера: %s', (_name, tags, expected) => {
    expect(idFor(tags), 'мастер есть, а спустится универсал').toBe(expected)
  })

  it('выбор человека сильнее автоподбора: он открыл ту дверь, которую хотел', () => {
    expect(idFor(['devops'], 'chef'), 'выбранного гнома подменили').toBe('chef')
  })

  it('«auto» означает подбор, а не гнома с таким именем', () => {
    expect(idFor(['devops'], 'auto')).toBe('devops')
    // ⚠️ И это не игра словами. `id` эксперта — свободная строка из админки (text PK),
    // никто не мешает завести гнома `auto`. Если слово не разобрать ДО поиска по id,
    // такой гном молча перехватит все автоподборы: человек нажимает «подобрать», а
    // получает всегда одного и того же. Порчу поймал стенд — без этого случая проверка
    // на «auto» оставалась зелёной на сломанном коде.
    const withTrap = [{ id: 'auto', domains: ['ловушка'] }, ...roster]
    expect(pickExpert(withTrap, ['devops'], 'auto')?.id, 'гном по имени «auto» перехватил подбор').toBe('devops')
  })

  it('мастера по теме нет — отвечает универсал, а не никто', () => {
    // Молчание хуже общего ответа: вопрос задан, и он про список, который у нас лежит.
    expect(idFor(['фотография'])).toBe('generalist')
  })

  it('несуществующий выбор не роняет подбор', () => {
    expect(idFor(['devops'], 'нет-такого'), 'опечатка в id оставила человека без ответа').toBe('devops')
  })
})
