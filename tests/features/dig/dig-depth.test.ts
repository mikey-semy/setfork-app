import { describe, expect, it } from 'vitest'
import { digDepth } from '@/features/dig/depth'
import { DIG_MAX_LEVEL, digLevelBrief } from '@/shared/ai/dig'

/**
 * РАЗГОВОР ИДЁТ ВГЛУБЬ, А НЕ ПО КРУГУ.
 *
 * В лоре «копать» — идти слой за слоем: причины и источники, потом механизм и
 * исключения, потом тонкости. Чат раскопки этой лестницы не знал вовсе: человек
 * спрашивал третий раз и получал ту же глубину, что в первый.
 *
 * ⚠️ Ремесло даёт УГОЛ (кто смотрит), слой даёт ГЛУБИНУ (насколько далеко). Это разные
 * оси; вместе они и есть «многогранность» из лоры — много мастеров на одном камне, и
 * каждый копает вглубь.
 */
describe('глубина раскопки', () => {
  it('первый вопрос — первый слой', () => {
    expect(digDepth([])).toBe(1)
  })

  it('гном ответил — следующий вопрос копает глубже', () => {
    expect(digDepth([{ role: 'user' }, { role: 'gnome' }])).toBe(2)
    expect(digDepth([{ role: 'user' }, { role: 'gnome' }, { role: 'user' }, { role: 'gnome' }])).toBe(3)
  })

  // ⚠️ Считаем ОТВЕТЫ, а не вопросы: сорвавшийся вызов (сбой модели, отказ по бюджету)
  // оставляет вопрос без ответа, и человек на самом деле никуда не спустился.
  it('вопрос без ответа не уводит глубже', () => {
    expect(digDepth([{ role: 'user' }]), 'сбой засчитан за пройденный слой').toBe(1)
    expect(digDepth([{ role: 'user' }, { role: 'user' }])).toBe(1)
  })

  it('ниже последнего слоя не опускаемся', () => {
    const long = Array.from({ length: 20 }, (_, i) => ({ role: i % 2 ? 'gnome' : 'user' }))
    expect(digDepth(long), 'глубина растёт бесконечно — дальше растёт болтовня, а не смысл').toBe(DIG_MAX_LEVEL)
  })

  it('у каждого слоя своя задача — иначе лестница ничего не меняет', () => {
    const briefs = [1, 2, 3].map(digLevelBrief)
    expect(new Set(briefs).size, 'слои описаны одинаково: глубина есть только на бумаге').toBe(3)
  })
})
