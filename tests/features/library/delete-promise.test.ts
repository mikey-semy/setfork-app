import { describe, expect, it } from 'vitest'
import { ru } from '@/shared/i18n/dict/ru'
import { en } from '@/shared/i18n/dict/en'

/**
 * ОБЕЩАНИЕ ПРИ УДАЛЕНИИ НЕ БОЛЬШЕ ТОГО, ЧТО СИСТЕМА ДЕЛАЕТ.
 *
 * Найдено вертикалью «собрать список» 27.08.2026 и оказалось тяжелейшим за проход.
 * Окно подтверждения обещало дословно: «Безвозвратно удаляет список — ВСЕ ВЕРСИИ, шаги,
 * прогоны, предложения, обсуждения и звёзды. Отменить нельзя». Замер прода в тот же день:
 * `main:list.json` удалённого списка читался спустя 37 дней, теги версий на месте.
 *
 * Причина в том, что копий истории ДВЕ: строки в Postgres и канон в git. Удаление списка
 * идёт мимо ядра (`db.delete` напрямую), значит до канона не доходит вовсе; стирает его
 * ручная уборка без расписания. То есть неправдой было именно то, что названо ПЕРВЫМ.
 *
 * Класс дефекта — «обещано и не сделано», и он выше «уничтожает» в нашей шкале цены:
 * там система ошибается молча, здесь заявляет результат вслух, в свою пользу, в момент
 * необратимого действия и с требованием подтверждения.
 *
 * Проверка держит не текст (его перепишут), а СОСТАВ обещания: раз в окне сказано
 * «безвозвратно», рядом обязана стоять оговорка про вторую копию. Пропадёт оговорка —
 * обещание снова станет больше дела, и это покраснеет.
 */

const PAIRS = [
  ['ru', ru],
  ['en', en],
] as const

describe('обещание при удалении списка', () => {
  it.each(PAIRS)('%s: рядом с «безвозвратно» стоит оговорка про вторую копию', (_lang, dict) => {
    const d = dict as unknown as Record<string, string>
    expect(d.deleteListCascade, 'обещание удаления должно существовать').toBeTruthy()
    expect(
      d.deleteListCanonNote,
      'у обещания «безвозвратно» нет оговорки про копию истории в git — а она стирается уборкой, не в тот же миг',
    ).toBeTruthy()
  })

  it.each(PAIRS)('%s: про внешнее зеркало сказано, что снять его мы не можем', (_lang, dict) => {
    const d = dict as unknown as Record<string, string>
    // Единственная часть удаления, где нужно ДЕЙСТВИЕ человека: внешнюю копию SetFork не
    // снимет никак — события об удалении ядро не получает, а токен зеркала уходит вместе
    // со строкой списка. Умолчать здесь значит обещать то, чего мы не делаем.
    expect(d.deleteListMirrorWarn, 'нет предупреждения про внешнее зеркало').toBeTruthy()
    expect(d.deleteListMirrorWarn.length, 'предупреждение обязано называть, что делать человеку').toBeGreaterThan(40)
  })
})
