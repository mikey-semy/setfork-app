/**
 * ЗОЛОТОЙ НАБОР для evals судящей машинерии.
 *
 * Каждый список здесь — не «пример данных», а ВОПРОС к нашим правилам: «узнаешь ли ты вот
 * это?». Именно эти правила решают, что уходит в паблик без человека, поэтому их дрейф опаснее
 * дрейфа генерации: плохой черновик увидит человек, а сломавшийся судья пропустит всё подряд.
 *
 * Фикстуры написаны руками, а не выгружены из базы: набор должен переживать очистку дев-БД и
 * читаться как утверждение о том, что мы считаем годным.
 */

export interface EvalItem {
  title: string
  desc?: string
  why?: string
  section?: string
  needsHuman?: boolean
  refs?: { url?: string }[]
}

export interface EvalList {
  /** Короткое имя случая — попадает в вывод, чтобы падение читалось без раскопок. */
  name: string
  title: string
  tags: string[]
  items: EvalItem[]
  /** Подтверждённо мёртвые ссылки (обычно считает link-health, здесь задаём явно). */
  deadLinks?: number
  /** Чего мы ЖДЁМ от правил. Несовпадение = регрессия судьи. */
  expect: {
    grade: 'stub' | 'start' | 'solid' | 'full'
    /** Пройдёт ли структурную часть планки по умолчанию (solid). */
    passesDefaultBar: boolean
  }
}

const ref = (n: number) => Array.from({ length: n }, (_, i) => ({ url: `https://example.com/${i}` }))
const full = (title: string, n: number, over: Partial<EvalItem> = {}): EvalItem[] =>
  Array.from({ length: n }, (_, i) => ({ title: `${title} — шаг ${i + 1}`, desc: 'что именно сделать и как понять, что получилось', why: 'зачем этот шаг', ...over }))

